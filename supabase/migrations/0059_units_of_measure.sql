-- Define or change one pack size. Upsert, because "a case is 144 not 120" is a
-- correction, not a new fact.
create or replace function public.set_product_uom(
  p_product_id bigint,
  p_uom_code text,
  p_conversion_factor numeric
) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_uom_id bigint;
  v_base_uom_id bigint;
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;
  if p_conversion_factor is null or p_conversion_factor <= 0 then
    raise exception 'conversion_factor must be greater than zero';
  end if;

  select id into v_uom_id from public.uoms
   where code = upper(btrim(coalesce(p_uom_code, ''))) and is_active;
  if v_uom_id is null then
    raise exception 'unknown unit %', p_uom_code;
  end if;

  select base_uom_id into v_base_uom_id from public.products where id = p_product_id;
  if v_base_uom_id is null then
    raise exception 'product % not found', p_product_id;
  end if;
  -- The base unit is one of itself by definition; letting it be edited would
  -- rescale every quantity already recorded against the product.
  if v_uom_id = v_base_uom_id and p_conversion_factor <> 1 then
    raise exception
      'the base unit is 1 by definition; change the base unit instead of its factor';
  end if;

  insert into public.product_uoms (product_id, uom_id, conversion_factor)
  values (p_product_id, v_uom_id, p_conversion_factor)
  on conflict (product_id, uom_id)
    do update set conversion_factor = excluded.conversion_factor;

  -- Any barcode that names this unit now means a different number of pieces.
  -- Touch them so the derive trigger recomputes rather than leaving a stale
  -- multiplier behind.
  update public.product_barcodes
     set uom_id = v_uom_id
   where product_id = p_product_id and uom_id = v_uom_id;

  perform public.log_audit('product.uom_set', 'product', p_product_id::text, null,
    jsonb_build_object('uom', upper(btrim(p_uom_code)),
                       'conversion_factor', p_conversion_factor));
  return true;
end;
$$;

revoke all on function public.set_product_uom(bigint, text, numeric) from public, anon;
grant execute on function public.set_product_uom(bigint, text, numeric)
  to authenticated, service_role;

create or replace function public.remove_product_uom(
  p_product_id bigint,
  p_uom_code text
) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_uom_id bigint;
  v_base_uom_id bigint;
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;

  select id into v_uom_id from public.uoms where code = upper(btrim(coalesce(p_uom_code, '')));
  if v_uom_id is null then
    raise exception 'unknown unit %', p_uom_code;
  end if;
  select base_uom_id into v_base_uom_id from public.products where id = p_product_id;
  if v_base_uom_id is null then
    raise exception 'product % not found', p_product_id;
  end if;
  if v_uom_id = v_base_uom_id then
    raise exception 'cannot remove the base unit';
  end if;
  if exists (select 1 from public.product_barcodes
              where product_id = p_product_id and uom_id = v_uom_id) then
    raise exception 'a barcode still uses unit %; remove the barcode first',
      upper(btrim(p_uom_code));
  end if;

  delete from public.product_uoms
   where product_id = p_product_id and uom_id = v_uom_id;

  perform public.log_audit('product.uom_removed', 'product', p_product_id::text,
    null, jsonb_build_object('uom', upper(btrim(p_uom_code))));
  return true;
end;
$$;

revoke all on function public.remove_product_uom(bigint, text) from public, anon;
grant execute on function public.remove_product_uom(bigint, text)
  to authenticated, service_role;

-- Changing the base unit rescales the meaning of every quantity already
-- recorded, so it is refused once there is any. That is the §37-15 rule —
-- a past transaction must not change meaning because master data changed.
create or replace function public.set_product_base_uom(
  p_product_id bigint,
  p_uom_code text
) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_uom_id bigint;
  v_old_id bigint;
  v_rows bigint;
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;

  select id into v_uom_id from public.uoms
   where code = upper(btrim(coalesce(p_uom_code, ''))) and is_active;
  if v_uom_id is null then
    raise exception 'unknown unit %', p_uom_code;
  end if;

  select base_uom_id into v_old_id from public.products where id = p_product_id;
  if v_old_id is null then
    raise exception 'product % not found', p_product_id;
  end if;
  if v_old_id = v_uom_id then
    return true;
  end if;

  select count(*) into v_rows from public.stock_movements where product_id = p_product_id;
  if v_rows > 0 then
    raise exception
      'product % already has % stock movements; changing its base unit would '
      'change what those quantities mean', p_product_id, v_rows;
  end if;

  update public.products set base_uom_id = v_uom_id, updated_at = now()
   where id = p_product_id;
  insert into public.product_uoms (product_id, uom_id, conversion_factor)
  values (p_product_id, v_uom_id, 1)
  on conflict (product_id, uom_id) do update set conversion_factor = 1;

  perform public.log_audit('product.base_uom_changed', 'product',
    p_product_id::text, null,
    jsonb_build_object('from_uom_id', v_old_id, 'to', upper(btrim(p_uom_code))));
  return true;
end;
$$;

revoke all on function public.set_product_base_uom(bigint, text) from public, anon;
grant execute on function public.set_product_base_uom(bigint, text)
  to authenticated, service_role;

