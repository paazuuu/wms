-- 0036 — Work orders / kitting / assembly (spec §46 checklist item 9)
--
-- "Work orders / assembly / kitting" were removed with InventorOS. Unlike
-- purchase/sales orders (0033/0034), which are deliberately external
-- documents that never move stock, a work order IS a stock-moving
-- operation — the internal counterpart: consume a set of component JANs,
-- produce one output JAN, entirely inside one warehouse. Scoped to
-- assembly/kitting only (many components → one output), the reading the
-- checklist bullet actually asks for; disassembly (one input → many
-- components) would reuse this same shape and is a natural follow-up, not
-- required for this to be useful on its own.
--
-- Nothing moves until `complete_work_order` — same discipline as
-- transfers/counts: draft → start → complete (or cancel before anything
-- moved). Two new stock_movements types record the two sides of the
-- transformation on the existing per-JAN ledger, so a kitted item's history
-- is traceable the same way a pick or an adjustment already is.
alter table public.stock_movements drop constraint stock_movements_movement_type_check;
alter table public.stock_movements add constraint stock_movements_movement_type_check
  check (movement_type = any (array[
    'OPENING', 'RECEIPT', 'RECEIPT_CANCEL', 'PUTAWAY', 'PICK', 'SHIP', 'SHIP_CANCEL',
    'ADJUST', 'COUNT', 'TRANSFER_IN', 'TRANSFER_OUT',
    'WORK_ORDER_CONSUME', 'WORK_ORDER_PRODUCE'
  ]));

create table public.work_orders (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id),
  wo_number text,
  warehouse_id bigint not null references public.warehouses(id),
  output_jan_code text not null,
  output_product_name text not null default '',
  output_quantity integer not null check (output_quantity > 0),
  status text not null default 'DRAFT'
    check (status in ('DRAFT', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
  note text,
  created_by uuid references public.app_users(id),
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index work_orders_number_idx
  on public.work_orders (wo_number) where wo_number is not null;
create index work_orders_warehouse_idx
  on public.work_orders (warehouse_id, status);

create table public.work_order_components (
  id bigint generated by default as identity primary key,
  work_order_id bigint not null references public.work_orders(id) on delete cascade,
  jan_code text not null,
  product_name text not null default '',
  quantity_required integer not null check (quantity_required > 0)
);

create index work_order_components_order_idx
  on public.work_order_components (work_order_id);

alter table public.work_orders enable row level security;
alter table public.work_order_components enable row level security;

create policy "work_orders: viewers can read"
  on public.work_orders for select
  to authenticated
  using (public.has_permission('work_order.view'));

create policy "work_order_components: viewers can read"
  on public.work_order_components for select
  to authenticated
  using (public.has_permission('work_order.view'));

-- No insert/update/delete policy on either table — every write goes through
-- the RPCs below, same discipline as purchase_orders/sales_orders.

insert into public.permissions (code, description)
values
  ('work_order.view', 'View work orders'),
  ('work_order.manage', 'Create, start, complete and cancel work orders');

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
  from public.roles r, public.permissions p
 where p.code = 'work_order.view'
   and r.code in ('system_admin', 'company_admin', 'warehouse_manager',
                   'inventory_controller', 'receiving', 'putaway_operator',
                   'picker', 'viewer');

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
  from public.roles r, public.permissions p
 where p.code = 'work_order.manage'
   and r.code in ('system_admin', 'company_admin', 'warehouse_manager',
                   'inventory_controller');

