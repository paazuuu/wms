create or replace function public.create_work_order(
  p_warehouse_id bigint,
  p_output_jan_code text,
  p_output_quantity integer,
  p_components jsonb,
  p_output_product_name text default '',
  p_note text default null
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_id bigint;
  v_company_id bigint;
  v_component jsonb;
  v_qty integer;
begin
  if not public.has_permission('work_order.manage') then
    raise exception 'not permitted: work_order.manage required';
  end if;
  if not exists (select 1 from public.warehouses where id = p_warehouse_id) then
    raise exception 'warehouse % not found', p_warehouse_id;
  end if;
  if p_output_jan_code is null or p_output_jan_code = '' then
    raise exception 'output_jan_code is required';
  end if;
  if p_output_quantity is null or p_output_quantity <= 0 then
    raise exception 'output_quantity must be positive';
  end if;
  if jsonb_typeof(p_components) is distinct from 'array' or jsonb_array_length(p_components) = 0 then
    raise exception 'at least one component is required';
  end if;

  select id into v_company_id from public.companies order by id limit 1;

  insert into public.work_orders
    (company_id, warehouse_id, output_jan_code, output_product_name, output_quantity,
     note, created_by)
  values
    (v_company_id, p_warehouse_id, p_output_jan_code, coalesce(p_output_product_name, ''),
     p_output_quantity, nullif(p_note, ''), auth.uid())
  returning id into v_id;

  update public.work_orders
     set wo_number = 'WO-' || lpad(v_id::text, 6, '0')
   where id = v_id;

  for v_component in select * from jsonb_array_elements(p_components) loop
    v_qty := coalesce((v_component->>'quantity_required')::int, 0);
    if v_qty > 0 and coalesce(v_component->>'jan_code', '') <> '' then
      insert into public.work_order_components
        (work_order_id, jan_code, product_name, quantity_required)
      values (
        v_id, v_component->>'jan_code', coalesce(v_component->>'product_name', ''), v_qty);
    end if;
  end loop;

  if not exists (select 1 from public.work_order_components where work_order_id = v_id) then
    raise exception 'at least one component with a positive quantity is required';
  end if;

  perform public.log_audit('work_order.created', 'work_order', v_id::text, p_warehouse_id,
    jsonb_build_object('output_jan_code', p_output_jan_code, 'output_quantity', p_output_quantity));

  return v_id;
end;
$$;

create or replace function public.start_work_order(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
begin
  if not public.has_permission('work_order.manage') then
    raise exception 'not permitted: work_order.manage required';
  end if;

  select status, warehouse_id into v_status, v_warehouse_id
    from public.work_orders where id = p_id;
  if v_status is null then raise exception 'work order % not found', p_id; end if;
  if v_status <> 'DRAFT' then
    raise exception 'work order % is % and cannot be started', p_id, v_status;
  end if;

  update public.work_orders set status = 'IN_PROGRESS', started_at = now() where id = p_id;
  perform public.log_audit(
    'work_order.started', 'work_order', p_id::text, v_warehouse_id, '{}'::jsonb);
  return true;
end;
$$;

create or replace function public.cancel_work_order(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
begin
  if not public.has_permission('work_order.manage') then
    raise exception 'not permitted: work_order.manage required';
  end if;

  select status, warehouse_id into v_status, v_warehouse_id
    from public.work_orders where id = p_id;
  if v_status is null then raise exception 'work order % not found', p_id; end if;
  if v_status not in ('DRAFT', 'IN_PROGRESS') then
    raise exception 'work order % is % and can no longer be cancelled', p_id, v_status;
  end if;

  update public.work_orders set status = 'CANCELLED' where id = p_id;
  perform public.log_audit('work_order.cancelled', 'work_order', p_id::text,
    v_warehouse_id, jsonb_build_object('was', v_status));
  return true;
end;
$$;

-- The only step that moves stock: every component's required quantity
-- leaves, the output quantity arrives — both on the existing ledger, so a
-- kitted item's history is traceable the same way a pick or count is.
create or replace function public.complete_work_order(p_id bigint)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
  v_output_jan text;
  v_output_name text;
  v_output_qty integer;
  r record;
  v_summary jsonb;
begin
  if not public.has_permission('work_order.manage') then
    raise exception 'not permitted: work_order.manage required';
  end if;

  select status, warehouse_id, output_jan_code, output_product_name, output_quantity
    into v_status, v_warehouse_id, v_output_jan, v_output_name, v_output_qty
    from public.work_orders where id = p_id;
  if v_status is null then raise exception 'work order % not found', p_id; end if;
  if v_status <> 'IN_PROGRESS' then
    raise exception 'work order % is % and cannot be completed', p_id, v_status;
  end if;

  for r in
    select jan_code, product_name, quantity_required
      from public.work_order_components
     where work_order_id = p_id
  loop
    perform public.apply_stock_movement(
      v_warehouse_id, r.jan_code, -r.quantity_required, 'WORK_ORDER_CONSUME',
      'work_order', p_id::text, r.product_name);
  end loop;

  perform public.apply_stock_movement(
    v_warehouse_id, v_output_jan, v_output_qty, 'WORK_ORDER_PRODUCE',
    'work_order', p_id::text, v_output_name);

  update public.work_orders
     set status = 'COMPLETED', completed_at = now()
   where id = p_id;

  select jsonb_build_object(
           'work_order_id', p_id,
           'output_jan_code', v_output_jan,
           'output_quantity', v_output_qty,
           'components_consumed', count(*))
    into v_summary
    from public.work_order_components where work_order_id = p_id;

  perform public.log_audit('work_order.completed', 'work_order', p_id::text,
    v_warehouse_id, v_summary);
  return v_summary;
end;
$$;

