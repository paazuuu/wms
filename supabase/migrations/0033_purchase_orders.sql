create or replace function public.create_purchase_order(
  p_supplier_name text,
  p_warehouse_id bigint,
  p_lines jsonb,
  p_supplier_id bigint default null,
  p_expected_date date default null,
  p_note text default null
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_id bigint;
  v_company_id bigint;
  v_line jsonb;
  v_qty integer;
begin
  if not public.has_permission('purchase_order.manage') then
    raise exception 'not permitted: purchase_order.manage required';
  end if;
  if p_supplier_name is null or p_supplier_name = '' then
    raise exception 'supplier_name is required';
  end if;
  if not exists (select 1 from public.warehouses where id = p_warehouse_id) then
    raise exception 'warehouse % not found', p_warehouse_id;
  end if;
  if jsonb_typeof(p_lines) is distinct from 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'at least one line is required';
  end if;

  select id into v_company_id from public.companies order by id limit 1;

  insert into public.purchase_orders
    (company_id, supplier_id, supplier_name, warehouse_id, expected_date, note, requested_by)
  values
    (v_company_id, p_supplier_id, p_supplier_name, p_warehouse_id, p_expected_date,
     nullif(p_note, ''), auth.uid())
  returning id into v_id;

  update public.purchase_orders
     set po_number = 'PO-' || lpad(v_id::text, 6, '0')
   where id = v_id;

  for v_line in select * from jsonb_array_elements(p_lines) loop
    v_qty := coalesce((v_line->>'quantity')::int, 0);
    if v_qty > 0 and coalesce(v_line->>'jan_code', '') <> '' then
      insert into public.purchase_order_lines
        (purchase_order_id, jan_code, product_name, quantity, unit_price)
      values (
        v_id, v_line->>'jan_code', coalesce(v_line->>'product_name', ''), v_qty,
        nullif(v_line->>'unit_price', '')::numeric);
    end if;
  end loop;

  if not exists (select 1 from public.purchase_order_lines where purchase_order_id = v_id) then
    raise exception 'at least one line with a positive quantity is required';
  end if;

  perform public.log_audit('purchase_order.created', 'purchase_order', v_id::text,
    p_warehouse_id, jsonb_build_object('supplier_name', p_supplier_name));

  return v_id;
end;
$$;

create or replace function public.submit_purchase_order(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
begin
  if not public.has_permission('purchase_order.manage') then
    raise exception 'not permitted: purchase_order.manage required';
  end if;

  select status, warehouse_id into v_status, v_warehouse_id
    from public.purchase_orders where id = p_id;
  if v_status is null then raise exception 'purchase order % not found', p_id; end if;
  if v_status <> 'DRAFT' then
    raise exception 'purchase order % is % and cannot be submitted', p_id, v_status;
  end if;

  update public.purchase_orders set status = 'SUBMITTED' where id = p_id;
  perform public.log_audit(
    'purchase_order.submitted', 'purchase_order', p_id::text, v_warehouse_id, '{}'::jsonb);
  return true;
end;
$$;

-- Self-approval refused once both requester and approver are known — same
-- guard as transfer_orders (0019), inactive while auth.uid() is null.
create or replace function public.approve_purchase_order(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
  v_requested_by uuid;
  v_approver uuid := auth.uid();
begin
  if not public.has_permission('purchase_order.approve') then
    raise exception 'not permitted: purchase_order.approve required';
  end if;

  select status, warehouse_id, requested_by
    into v_status, v_warehouse_id, v_requested_by
    from public.purchase_orders where id = p_id;
  if v_status is null then raise exception 'purchase order % not found', p_id; end if;
  if v_status <> 'SUBMITTED' then
    raise exception 'purchase order % is % and cannot be approved', p_id, v_status;
  end if;
  if v_requested_by is not null and v_approver is not null and v_requested_by = v_approver then
    raise exception 'a purchase order cannot be approved by the person who requested it';
  end if;

  update public.purchase_orders
     set status = 'APPROVED', approved_by = v_approver, approved_at = now()
   where id = p_id;
  perform public.log_audit(
    'purchase_order.approved', 'purchase_order', p_id::text, v_warehouse_id, '{}'::jsonb);
  return true;
end;
$$;

create or replace function public.reject_purchase_order(p_id bigint, p_reason text default null)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
begin
  if not public.has_permission('purchase_order.approve') then
    raise exception 'not permitted: purchase_order.approve required';
  end if;

  select status, warehouse_id into v_status, v_warehouse_id
    from public.purchase_orders where id = p_id;
  if v_status is null then raise exception 'purchase order % not found', p_id; end if;
  if v_status <> 'SUBMITTED' then
    raise exception 'purchase order % is % and cannot be rejected', p_id, v_status;
  end if;

  update public.purchase_orders set status = 'REJECTED' where id = p_id;
  perform public.log_audit('purchase_order.rejected', 'purchase_order', p_id::text,
    v_warehouse_id, jsonb_build_object('reason', p_reason));
  return true;
end;
$$;

-- DRAFT, SUBMITTED and APPROVED can all be cancelled — nothing has moved
-- yet in any of those states (a PO never moves stock on its own).
create or replace function public.cancel_purchase_order(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
begin
  if not public.has_permission('purchase_order.manage') then
    raise exception 'not permitted: purchase_order.manage required';
  end if;

  select status, warehouse_id into v_status, v_warehouse_id
    from public.purchase_orders where id = p_id;
  if v_status is null then raise exception 'purchase order % not found', p_id; end if;
  if v_status not in ('DRAFT', 'SUBMITTED', 'APPROVED') then
    raise exception 'purchase order % is % and can no longer be cancelled', p_id, v_status;
  end if;

  update public.purchase_orders set status = 'CANCELLED' where id = p_id;
  perform public.log_audit('purchase_order.cancelled', 'purchase_order', p_id::text,
    v_warehouse_id, jsonb_build_object('was', v_status));
  return true;
end;
$$;

-- Bookkeeping close only — no stock movement. Actual receipt still goes
-- through the existing delivery-plan/reconciliation flow, unchanged.
create or replace function public.complete_purchase_order(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_status text;
  v_warehouse_id bigint;
begin
  if not public.has_permission('purchase_order.manage') then
    raise exception 'not permitted: purchase_order.manage required';
  end if;

  select status, warehouse_id into v_status, v_warehouse_id
    from public.purchase_orders where id = p_id;
  if v_status is null then raise exception 'purchase order % not found', p_id; end if;
  if v_status <> 'APPROVED' then
    raise exception 'purchase order % is % and cannot be completed', p_id, v_status;
  end if;

  update public.purchase_orders set status = 'COMPLETED' where id = p_id;
  perform public.log_audit(
    'purchase_order.completed', 'purchase_order', p_id::text, v_warehouse_id, '{}'::jsonb);
  return true;
end;
$$;

