-- 0033 — Purchase orders (spec §46 checklist item 6)
--
-- "Purchase orders" were removed with InventorOS and never rebuilt on
-- Supabase. `delivery_plans` (0001+) is a related but distinct concept — an
-- *expected shipment*, usually created by importing a delivery note
-- (already shipped, quantities mostly known) and used for QC reconciliation
-- against what physically arrives. A purchase order is the earlier-stage
-- document: what was *ordered* from a supplier, before it ships. This is a
-- deliberately self-contained order-lifecycle module — draft → submit →
-- approve/reject → (cancel) → complete — that does not move stock and is
-- not wired into delivery_plans/reconciliation; "complete" here is a
-- bookkeeping close, not a receiving event. Wiring a PO into the existing
-- receiving flow (e.g. pre-filling a delivery plan from an approved PO) is
-- a natural follow-up, not required for this to be useful on its own.
--
-- Follows the state-machine and self-approval-refused shape transfer_orders
-- (0019) established, but grants execute directly to `authenticated` with
-- `has_permission()` checks inside — the pattern every RPC since 0024 (real
-- sign-in) uses, not 0019's now-superseded service_role-only grants.
create table public.purchase_orders (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id),
  po_number text,
  supplier_id bigint references public.delivery_suppliers(id),
  supplier_name text not null,
  warehouse_id bigint not null references public.warehouses(id),
  status text not null default 'DRAFT' check (status in (
    'DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
  order_date date not null default current_date,
  expected_date date,
  note text,
  requested_by uuid references public.app_users(id),
  approved_by uuid references public.app_users(id),
  approved_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index purchase_orders_number_idx
  on public.purchase_orders (po_number) where po_number is not null;
create index purchase_orders_warehouse_idx
  on public.purchase_orders (warehouse_id, status);

create table public.purchase_order_lines (
  id bigint generated by default as identity primary key,
  purchase_order_id bigint not null references public.purchase_orders(id) on delete cascade,
  jan_code text not null,
  product_name text not null default '',
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2),
  note text
);

create index purchase_order_lines_order_idx
  on public.purchase_order_lines (purchase_order_id);

alter table public.purchase_orders enable row level security;
alter table public.purchase_order_lines enable row level security;

create policy "purchase_orders: viewers can read"
  on public.purchase_orders for select
  to authenticated
  using (public.has_permission('purchase_order.view'));

create policy "purchase_order_lines: viewers can read"
  on public.purchase_order_lines for select
  to authenticated
  using (public.has_permission('purchase_order.view'));

-- No insert/update/delete policy on either table — every write goes through
-- the RPCs below, same discipline as attachments/connectors/products.

insert into public.permissions (code, description)
values
  ('purchase_order.view', 'View purchase orders'),
  ('purchase_order.manage', 'Create, submit, cancel and complete purchase orders'),
  ('purchase_order.approve', 'Approve or reject a submitted purchase order');

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
  from public.roles r, public.permissions p
 where p.code = 'purchase_order.view'
   and r.code in ('system_admin', 'company_admin', 'warehouse_manager',
                   'inventory_controller', 'receiving', 'viewer');

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
  from public.roles r, public.permissions p
 where p.code = 'purchase_order.manage'
   and r.code in ('system_admin', 'company_admin', 'warehouse_manager',
                   'inventory_controller');

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
  from public.roles r, public.permissions p
 where p.code = 'purchase_order.approve'
   and r.code in ('system_admin', 'company_admin', 'warehouse_manager');

