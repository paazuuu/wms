-- Phase A, step 9: the location tree (§7, §8).
--
-- The current shape is exactly two levels deep:
--
--     Warehouse -> Zone -> Bin
--
-- §7 says keep it and make it a general tree, so that a warehouse which is
-- actually laid out as
--
--     Warehouse -> Zone -> Aisle -> Rack -> Shelf -> Bin
--
-- can say so instead of flattening three of those levels into a bin code and
-- hoping everyone reads it the same way. §8 adds the second half: a location
-- has a *type*, so "can this shelf hold ordinary stock?" is a column rather
-- than a convention, and RECEIVING / QC / SHIPPING / TRANSIT / DAMAGED become
-- real places that stock can sit in rather than states invented per screen.
--
-- HOW THIS FITS WHAT IS ALREADY HERE
--
-- `bins` is what `bin_stock` keys on and what every put-away RPC references.
-- Rewriting those onto a new table would be a large change to working code for
-- no gain today, so this migration does not touch them. Instead:
--
--     locations   the tree, canonical for STRUCTURE
--     bins        unchanged, canonical for BIN-LEVEL QUANTITY (bin_stock)
--
-- Every zone and every bin gets a location row, kept in step by triggers, and
-- the location carries a back-pointer (`zone_id` / `bin_id`) so the two can
-- always be lined up. Locations that are not bins — an aisle, a rack, a virtual
-- RECEIVING area — simply have no back-pointer. The sync is one-way on purpose:
-- bins and zones are what the running system writes, so they lead and the tree
-- follows. When Phase B moves put-away onto locations, that migration flips the
-- direction and says so.
--
-- WHAT THIS DOES NOT DO
--
-- It does not move quantity. `stock_units.bin_id` stays null (0061) and
-- `bin_stock` stays the bin-level answer. A tree with no stock hanging off it is
-- still worth having — it is what makes put-away suggestion, pick paths and
-- zone-level counting possible later — but pretending the quantity moved with
-- it would be the double count §5 warns about.

-- ---------------------------------------------------------------------------
-- 1. Location types (§8)
-- ---------------------------------------------------------------------------

-- A table rather than a check constraint, because the point of §8 is that the
-- behaviour of a type is *data*: "can stock be picked from here" is answered by
-- a column, not by a list of codes written into each query that asks.
create table if not exists public.location_types (
  code text primary key,
  name text not null,
  -- The defaults a new location of this type starts with. They are defaults,
  -- not rules: a particular shelf can be marked unpickable without inventing a
  -- type for it.
  default_pickable boolean not null default true,
  default_receivable boolean not null default false,
  default_shipping boolean not null default false,
  default_quarantine boolean not null default false,
  default_virtual boolean not null default false,
  sort_order integer not null default 100,
  constraint location_types_code_check check (code = upper(btrim(code)) and code <> '')
);

