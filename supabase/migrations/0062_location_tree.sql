-- §26's one resolver again: the label on a shelf is read with the same gun as
-- the label on a carton, and the operator should not have to know which screen
-- turns which one into an answer. Answered after products and serials, because
-- a location barcode is the rarer scan and an overlap should favour the goods.
create or replace function public.resolve_barcode(p_barcode text)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_code text;
  v_raw text := nullif(upper(btrim(coalesce(p_barcode, ''))), '');
  v_result jsonb;
begin
  if not (public.has_permission('product.view')
          or public.has_permission('inventory.view')) then
    raise exception 'not permitted: product.view required';
  end if;

  v_code := public.normalize_barcode(p_barcode);
  if v_code is null then
    return jsonb_build_object('kind', 'unknown', 'barcode', p_barcode);
  end if;

  select jsonb_build_object(
           'kind', 'product',
           'barcode', b.barcode,
           'barcode_type', b.barcode_type,
           'quantity_per_scan', b.quantity_per_scan,
           'uom', (select u.code from public.uoms u where u.id = b.uom_id),
           'base_uom', (select u.code from public.uoms u where u.id = p.base_uom_id),
           'is_primary', b.is_primary,
           'product_id', p.id,
           'jan_code', p.jan_code,
           'sku', p.sku,
           'name', p.name,
           'category', p.category,
           'tracking_mode', p.tracking_mode,
           'status', p.status)
    into v_result
    from public.product_barcodes b
    join public.products p on p.id = b.product_id
   where b.barcode = v_code;
  if v_result is not null then
    return v_result;
  end if;

  select jsonb_build_object(
           'kind', 'serial',
           'barcode', sn.serial_number,
           'serial_id', sn.id,
           'serial_number', sn.serial_number,
           'serial_status', sn.status,
           'lot_id', sn.lot_id,
           'lot_code', (select l.lot_code from public.lots l where l.id = sn.lot_id),
           'expiry_date', (select l.expiry_date from public.lots l where l.id = sn.lot_id),
           'quantity_per_scan', 1,
           'base_uom', (select u.code from public.uoms u where u.id = p.base_uom_id),
           'product_id', p.id,
           'jan_code', p.jan_code,
           'sku', p.sku,
           'name', p.name,
           'category', p.category,
           'tracking_mode', p.tracking_mode,
           'status', p.status)
    into v_result
    from public.serial_numbers sn
    join public.products p on p.id = sn.product_id
   where sn.serial_number in (v_raw, v_code)
   order by case when sn.serial_number = v_raw then 0 else 1 end
   limit 1;
  if v_result is not null then
    return v_result;
  end if;

  -- Scoped, unlike the two above: a product is master data any operator may
  -- look up, but a location belongs to a building, and which buildings this
  -- operator may see is the §37 rule every other warehouse read follows.
  select jsonb_build_object(
           'kind', 'location',
           'barcode', coalesce(l.barcode, l.code),
           'location_id', l.id,
           'code', l.code,
           'name', l.name,
           'location_type', l.location_type,
           'warehouse_id', l.warehouse_id,
           'bin_id', l.bin_id,
           'zone_id', l.zone_id,
           'is_active', l.is_active,
           'pickable', l.pickable,
           'receivable', l.receivable,
           'quarantine', l.quarantine,
           'is_virtual', l.is_virtual)
    into v_result
    from public.locations l
   where (l.barcode = v_code or upper(l.code) in (v_raw, v_code))
     and public.can_access_warehouse(l.warehouse_id)
   order by case when l.barcode = v_code then 0 else 1 end, l.id
   limit 1;

  return coalesce(v_result,
                  jsonb_build_object('kind', 'unknown', 'barcode', v_code));
end;
$$;

revoke all on function public.resolve_barcode(text) from public, anon;
grant execute on function public.resolve_barcode(text) to authenticated, service_role;

