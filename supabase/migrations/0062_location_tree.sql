create or replace function public.create_location(
  p_warehouse_id bigint,
  p_code text,
  p_name text default null,
  p_location_type text default 'STORAGE',
  p_parent_code text default null,
  p_barcode text default null,
  p_pickable boolean default null,
  p_receivable boolean default null,
  p_shipping boolean default null,
  p_quarantine boolean default null,
  p_is_virtual boolean default null
) returns bigint
language plpgsql security definer set search_path = ''
as $$
declare
  v_company_id bigint;
  v_type record;
  v_parent bigint;
  v_code text := btrim(coalesce(p_code, ''));
  v_id bigint;
begin
  if not public.has_permission('warehouse.manage') then
    raise exception 'not permitted: warehouse.manage required';
  end if;
  if not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;
  if v_code = '' then
    raise exception 'code is required';
  end if;

  select company_id into v_company_id from public.warehouses where id = p_warehouse_id;
  if v_company_id is null then
    raise exception 'warehouse % not found', p_warehouse_id;
  end if;

  select * into v_type from public.location_types
   where code = upper(btrim(coalesce(p_location_type, 'STORAGE')));
  if v_type is null then
    raise exception 'unknown location type %', p_location_type;
  end if;

  if nullif(btrim(coalesce(p_parent_code, '')), '') is not null then
    select id into v_parent from public.locations
     where warehouse_id = p_warehouse_id and code = btrim(p_parent_code);
    if v_parent is null then
      raise exception 'parent location % not found in this warehouse', p_parent_code;
    end if;
  end if;

  -- The flags default from the type (§8's point) and are overridden only where
  -- the caller actually said something, which is why they arrive nullable.
  insert into public.locations (
    company_id, warehouse_id, parent_id, code, name, location_type, barcode,
    pickable, receivable, shipping, quarantine, is_virtual)
  values (
    v_company_id, p_warehouse_id, v_parent, v_code,
    nullif(btrim(coalesce(p_name, '')), ''), v_type.code,
    public.normalize_barcode(p_barcode),
    coalesce(p_pickable, v_type.default_pickable),
    coalesce(p_receivable, v_type.default_receivable),
    coalesce(p_shipping, v_type.default_shipping),
    coalesce(p_quarantine, v_type.default_quarantine),
    coalesce(p_is_virtual, v_type.default_virtual))
  returning id into v_id;

  perform public.log_audit('warehouse.location_created', 'location', v_id::text,
    p_warehouse_id, jsonb_build_object('code', v_code, 'type', v_type.code,
                                       'parent_code', p_parent_code));
  return v_id;
end;
$$;

revoke all on function public.create_location(
  bigint, text, text, text, text, text, boolean, boolean, boolean, boolean, boolean)
  from public, anon;
grant execute on function public.create_location(
  bigint, text, text, text, text, text, boolean, boolean, boolean, boolean, boolean)
  to authenticated, service_role;

-- Only the fields a caller names are changed; everything else keeps its value,
-- so this can be used to flip one flag without restating the row.
create or replace function public.update_location(
  p_location_id bigint,
  p_name text default null,
  p_location_type text default null,
  p_parent_code text default null,
  p_barcode text default null,
  p_is_active boolean default null,
  p_pickable boolean default null,
  p_receivable boolean default null,
  p_shipping boolean default null,
  p_quarantine boolean default null
) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_loc record;
  v_parent bigint;
  v_type text;
begin
  if not public.has_permission('warehouse.manage') then
    raise exception 'not permitted: warehouse.manage required';
  end if;
  select * into v_loc from public.locations where id = p_location_id;
  if v_loc is null then
    raise exception 'location % not found', p_location_id;
  end if;
  if not public.can_access_warehouse(v_loc.warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;

  if nullif(btrim(coalesce(p_location_type, '')), '') is not null then
    select code into v_type from public.location_types
     where code = upper(btrim(p_location_type));
    if v_type is null then
      raise exception 'unknown location type %', p_location_type;
    end if;
  end if;

  if nullif(btrim(coalesce(p_parent_code, '')), '') is not null then
    select id into v_parent from public.locations
     where warehouse_id = v_loc.warehouse_id and code = btrim(p_parent_code);
    if v_parent is null then
      raise exception 'parent location % not found in this warehouse', p_parent_code;
    end if;
  end if;

  update public.locations
     set name = coalesce(nullif(btrim(coalesce(p_name, '')), ''), name),
         location_type = coalesce(v_type, location_type),
         parent_id = coalesce(v_parent, parent_id),
         barcode = coalesce(public.normalize_barcode(p_barcode), barcode),
         is_active = coalesce(p_is_active, is_active),
         pickable = coalesce(p_pickable, pickable),
         receivable = coalesce(p_receivable, receivable),
         shipping = coalesce(p_shipping, shipping),
         quarantine = coalesce(p_quarantine, quarantine),
         updated_at = now()
   where id = p_location_id;

  perform public.log_audit('warehouse.location_updated', 'location',
    p_location_id::text, v_loc.warehouse_id,
    jsonb_build_object('type', v_type, 'parent_code', p_parent_code,
                       'is_active', p_is_active));
  return true;
end;
$$;

revoke all on function public.update_location(
  bigint, text, text, text, text, boolean, boolean, boolean, boolean, boolean)
  from public, anon;
grant execute on function public.update_location(
  bigint, text, text, text, text, boolean, boolean, boolean, boolean, boolean)
  to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 5. Reading the tree
-- ---------------------------------------------------------------------------

-- One node with its whole subtree nested inside it. Recursive rather than a
-- recursive CTE: a CTE walks *down* a tree easily but has to be turned inside
-- out to build JSON *up* from the leaves, and the inside-out version is the kind
-- of query that silently loses grandchildren. The depth is bounded by the
-- no-cycle trigger's 32 levels.
--
-- `on_hand` is read from `bin_stock` for nodes that are bins, because that is
-- still the canonical bin-level quantity (0061). Nodes that are not bins report
-- null rather than 0: "no stock here" and "this is not somewhere stock is
-- counted" are different answers.
create or replace function public.location_subtree(
  p_location_id bigint,
  p_include_inactive boolean default false
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_node jsonb;
begin
  select jsonb_build_object(
           'id', l.id, 'code', l.code, 'name', l.name,
           'location_type', l.location_type,
           'barcode', l.barcode,
           'is_active', l.is_active,
           'pickable', l.pickable, 'receivable', l.receivable,
           'shipping', l.shipping, 'quarantine', l.quarantine,
           'is_virtual', l.is_virtual,
           'zone_id', l.zone_id, 'bin_id', l.bin_id,
           'on_hand', case when l.bin_id is null then null
                      else (select coalesce(sum(bs.on_hand), 0)
                              from public.bin_stock bs where bs.bin_id = l.bin_id)
                      end,
           'children', coalesce((
             select jsonb_agg(public.location_subtree(c.id, p_include_inactive)
                              order by c.code)
               from public.locations c
              where c.parent_id = l.id
                and (coalesce(p_include_inactive, false) or c.is_active)),
             '[]'::jsonb))
    into v_node
    from public.locations l
   where l.id = p_location_id;
  return v_node;
end;
$$;

revoke all on function public.location_subtree(bigint, boolean)
  from public, anon, authenticated;

-- Nested, not flat: the shape of the answer is the shape of the warehouse, and
-- a client that has to rebuild the hierarchy from parent ids will do it
-- differently on every screen.
create or replace function public.location_tree(
  p_warehouse_id bigint,
  p_include_inactive boolean default false
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_all boolean := coalesce(p_include_inactive, false);
begin
  if not (public.has_permission('warehouse.view')
          or public.has_permission('inventory.view')) then
    raise exception 'not permitted: warehouse.view required';
  end if;
  if not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;

  return coalesce((
    select jsonb_agg(public.location_subtree(l.id, v_all) order by l.code)
      from public.locations l
     where l.warehouse_id = p_warehouse_id
       and l.parent_id is null
       and (v_all or l.is_active)), '[]'::jsonb);
end;
$$;

revoke all on function public.location_tree(bigint, boolean) from public, anon;
grant execute on function public.location_tree(bigint, boolean)
  to authenticated, service_role;

