create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies (id),
  warehouse_id bigint not null references public.warehouses (id) on delete cascade,
  -- Null means "directly under the warehouse". The warehouse itself is not a
  -- row here: it already exists, and giving it a second identity in this table
  -- would mean two places to keep its name.
  parent_id bigint,
  code text not null,
  name text,
  location_type text not null default 'STORAGE' references public.location_types (code),
  -- What a scan gun reads off the shelf label. Normalized the same way a
  -- product barcode is (0057), so the one resolver can answer for both.
  barcode text,
  is_active boolean not null default true,
  pickable boolean not null default true,
  receivable boolean not null default false,
  shipping boolean not null default false,
  quarantine boolean not null default false,
  is_virtual boolean not null default false,
  -- Back-pointers to the rows the running system still writes. At most one of
  -- them is set; a rack or a virtual RECEIVING area has neither.
  zone_id bigint unique references public.zones (id) on delete cascade,
  bin_id bigint unique references public.bins (id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint locations_code_check check (code = btrim(code) and code <> ''),
  constraint locations_warehouse_code_key unique (warehouse_id, code),
  constraint locations_warehouse_barcode_key unique (warehouse_id, barcode),
  -- The FK target that keeps a parent in the same warehouse as its child.
  constraint locations_warehouse_id_key unique (warehouse_id, id),
  constraint locations_parent_fk foreign key (warehouse_id, parent_id)
    references public.locations (warehouse_id, id) on delete restrict,
  constraint locations_not_own_parent_check check (parent_id is distinct from id),
  constraint locations_single_source_check check (zone_id is null or bin_id is null)
);

create index if not exists locations_parent_idx on public.locations (parent_id);
create index if not exists locations_warehouse_type_idx
  on public.locations (warehouse_id, location_type);

alter table public.locations enable row level security;

drop policy if exists "read locations" on public.locations;
create policy "read locations" on public.locations
  for select to authenticated
  using ((public.has_permission('warehouse.view')
          or public.has_permission('inventory.view'))
         and public.can_access_warehouse(warehouse_id));

-- The FK stops a location pointing at a parent in another warehouse and the
-- check stops it pointing at itself, but neither can see a longer cycle:
-- A -> B -> A satisfies both. Walking up is the only way to know, and the depth
-- limit doubles as the guard against a tree someone has nested absurdly.
create or replace function public.locations_no_cycle()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_parent bigint := new.parent_id;
  v_steps integer := 0;
begin
  while v_parent is not null loop
    if v_parent = new.id then
      raise exception 'location % cannot be its own ancestor', new.code;
    end if;
    v_steps := v_steps + 1;
    if v_steps > 32 then
      raise exception 'location tree deeper than 32 levels under %', new.code;
    end if;
    select parent_id into v_parent from public.locations where id = v_parent;
  end loop;
  return new;
end;
$$;

drop trigger if exists locations_no_cycle on public.locations;
create trigger locations_no_cycle
  before insert or update of parent_id on public.locations
  for each row execute function public.locations_no_cycle();

-- ---------------------------------------------------------------------------
-- 3. Keeping the tree in step with zones and bins
-- ---------------------------------------------------------------------------

-- A code is unique within a warehouse so that scanning one, or naming a parent
-- by it, has exactly one answer. That makes a collision possible in principle —
-- a zone and a bin both called "A" — and this sync must never be the reason a
-- warehouse edit fails, so it disambiguates instead of raising. In a warehouse
-- named sensibly this never fires.
create or replace function public.location_code_for(
  p_warehouse_id bigint,
  p_code text,
  p_zone_id bigint,
  p_bin_id bigint
) returns text
language sql stable security definer set search_path = ''
as $$
  select case when exists (
           select 1 from public.locations l
            where l.warehouse_id = p_warehouse_id
              and l.code = btrim(p_code)
              and l.zone_id is distinct from p_zone_id
              and l.bin_id is distinct from p_bin_id)
         then btrim(p_code) || '#' || coalesce(p_bin_id, p_zone_id)::text
         else btrim(p_code) end;
$$;

revoke all on function public.location_code_for(bigint, text, bigint, bigint)
  from public, anon, authenticated;

-- A zone becomes a location directly under the warehouse; a bin becomes one
-- under its zone. Two functions rather than one, because the two rows differ in
-- what they carry (a zone has a name, a bin has a type and an active flag), and
-- both are idempotent on the back-pointer — so renaming a bin moves its location
-- instead of leaving a stale one behind.
create or replace function public.sync_zone_location()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_company_id bigint;
begin
  select company_id into v_company_id from public.warehouses where id = new.warehouse_id;

  insert into public.locations (company_id, warehouse_id, code, name,
                                location_type, zone_id)
  values (v_company_id, new.warehouse_id,
          public.location_code_for(new.warehouse_id, new.code, new.id, null),
          new.name, 'STORAGE', new.id)
  on conflict (zone_id) do update
     set code = excluded.code, name = excluded.name, updated_at = now();
  return null;
end;
$$;

drop trigger if exists zones_sync_location on public.zones;
create trigger zones_sync_location
  after insert or update of code, name, warehouse_id on public.zones
  for each row execute function public.sync_zone_location();

create or replace function public.sync_bin_location()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_company_id bigint;
  v_parent bigint;
  v_type text;
begin
  select company_id into v_company_id from public.warehouses where id = new.warehouse_id;
  if new.zone_id is not null then
    select id into v_parent from public.locations where zone_id = new.zone_id;
  end if;
  -- `bins.bin_type` is free text today and predates the type vocabulary, so it
  -- is taken as a hint and ignored when it names nothing this schema knows.
  select code into v_type from public.location_types
   where code = upper(btrim(coalesce(new.bin_type, '')));

  insert into public.locations (company_id, warehouse_id, parent_id, code,
                                location_type, is_active, bin_id)
  values (v_company_id, new.warehouse_id, v_parent,
          public.location_code_for(new.warehouse_id, new.code, null, new.id),
          coalesce(v_type, 'STORAGE'), coalesce(new.is_active, true), new.id)
  on conflict (bin_id) do update
     set code = excluded.code,
         parent_id = excluded.parent_id,
         is_active = excluded.is_active,
         updated_at = now();
  return null;
end;
$$;

drop trigger if exists bins_sync_location on public.bins;
create trigger bins_sync_location
  after insert or update of code, zone_id, bin_type, is_active, warehouse_id
  on public.bins
  for each row execute function public.sync_bin_location();

-- Backfill, zones first so the bins have parents to find. Re-runnable: both
-- upserts key on the back-pointer.
do $backfill$
declare z record; b record;
begin
  for z in select * from public.zones loop
    insert into public.locations (company_id, warehouse_id, code, name,
                                  location_type, zone_id)
    select w.company_id, z.warehouse_id, z.code, z.name, 'STORAGE', z.id
      from public.warehouses w where w.id = z.warehouse_id
    on conflict (zone_id) do update
       set code = excluded.code, name = excluded.name, updated_at = now();
  end loop;

  for b in select * from public.bins loop
    insert into public.locations (company_id, warehouse_id, parent_id, code,
                                  location_type, is_active, bin_id)
    select w.company_id, b.warehouse_id,
           (select l.id from public.locations l where l.zone_id = b.zone_id),
           b.code,
           coalesce((select t.code from public.location_types t
                      where t.code = upper(btrim(coalesce(b.bin_type, '')))), 'STORAGE'),
           coalesce(b.is_active, true), b.id
      from public.warehouses w where w.id = b.warehouse_id
    on conflict (bin_id) do update
       set code = excluded.code, parent_id = excluded.parent_id,
           is_active = excluded.is_active, updated_at = now();
  end loop;
end $backfill$;

