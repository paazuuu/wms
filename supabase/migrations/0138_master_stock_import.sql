-- ------------------------------------------------------------ the import
create or replace function public.master_import_start(
  p_original_name text, p_original_type text default null, p_source text default null,
  p_document_id bigint default null, p_supplier_id bigint default null)
returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_id bigint;
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;
  insert into public.master_imports (company_id, original_name, original_type, source, document_id, supplier_id)
  values ((select id from public.companies order by id limit 1), public.tidy_text(p_original_name),
          public.tidy_text(p_original_type), public.tidy_text(p_source), p_document_id, p_supplier_id)
  returning id into v_id;
  return v_id;
end;
$$;

-- A file kept with the import: the one chosen, the sheet the reading was
-- turned into, or the sheet a person corrected and sent back.
create or replace function public.master_import_attach(p_id bigint, p_kind text, p_name text, p_path text)
returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;
  if p_kind not in ('original', 'converted', 'corrected') then
    raise exception 'unknown file kind %', p_kind;
  end if;
  if p_path is null or p_path not like 'imports/' || p_id || '/%' then
    raise exception 'the file must be kept under imports/%/', p_id;
  end if;
  update public.master_imports set
    original_name = case when p_kind = 'original' then coalesce(public.tidy_text(p_name), original_name) else original_name end,
    original_path = case when p_kind = 'original' then p_path else original_path end,
    converted_name = case when p_kind = 'converted' then public.tidy_text(p_name) else converted_name end,
    converted_path = case when p_kind = 'converted' then p_path else converted_path end,
    corrected_name = case when p_kind = 'corrected' then public.tidy_text(p_name) else corrected_name end,
    corrected_path = case when p_kind = 'corrected' then p_path else corrected_path end,
    updated_at = now()
   where id = p_id and status in ('reading', 'stopped');
  if not found then
    raise exception 'import % not found or already registered', p_id;
  end if;
  return true;
end;
$$;

-- Stopped before anything was written: what was wrong, kept on the import.
create or replace function public.master_import_stop(p_id bigint, p_issues jsonb, p_line_count integer default null)
returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;
  update public.master_imports set
    status = 'stopped',
    issues = case when jsonb_typeof(p_issues) = 'array' then p_issues else '[]'::jsonb end,
    line_count = coalesce(p_line_count, line_count),
    updated_at = now()
   where id = p_id and status in ('reading', 'stopped');
  return found;
end;
$$;

create or replace function public.master_import_cancel(p_id bigint)
returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if not public.has_permission('product.manage') then
    raise exception 'not permitted: product.manage required';
  end if;
  update public.master_imports set status = 'cancelled', updated_at = now()
   where id = p_id and status in ('reading', 'stopped');
  return found;
end;
$$;

-- The imports, newest first, with their files and what each stage did.
create or replace function public.master_imports_list(p_limit integer default 50)
returns jsonb
language sql stable security definer set search_path = '' as $$
  select case when not public.master_import_viewer() then '[]'::jsonb else coalesce((
    select jsonb_agg(to_jsonb(x) order by x.created_at desc, x.id desc)
      from (select m.id, m.status, m.source, m.supplier_id, s.name as supplier_name, m.warehouse_id,
                   w.name as warehouse_name, m.original_name, m.original_path, m.converted_name, m.converted_path,
                   m.corrected_name, m.corrected_path, m.line_count, m.issues, m.master_created, m.master_updated,
                   m.master_mapped, m.stock_lines, m.stock_added, m.created_at, m.master_at, m.stock_at,
                   (select coalesce(u.name, u.email) from public.app_users u where u.id = m.created_by) as created_by_name
              from public.master_imports m
              left join public.delivery_suppliers s on s.id = m.supplier_id
              left join public.warehouses w on w.id = m.warehouse_id
             order by m.created_at desc, m.id desc
             limit greatest(1, least(coalesce(p_limit, 50), 200))) x), '[]'::jsonb) end;
$$;

-- One import with its lines; with a warehouse, each line also carries the
-- stock that product has there now (for the second stage).
create or replace function public.master_import_detail(p_id bigint, p_warehouse_id bigint default null)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_head jsonb;
begin
  if not public.master_import_viewer() then
    raise exception 'not permitted: product.view required';
  end if;
  if p_warehouse_id is not null and not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;
  select to_jsonb(m) - 'company_id' into v_head from public.master_imports m where m.id = p_id;
  if v_head is null then
    raise exception 'import % not found', p_id;
  end if;
  return v_head || jsonb_build_object('lines', coalesce((
    select jsonb_agg(jsonb_build_object(
             'line_no', l.line_no, 'jan_code', l.jan_code, 'product_id', l.product_id,
             -- The name comes from 商品マスタ, not from the file.
             'name', p.name, 'name_en', p.name_en, 'maker', p.maker, 'sku', p.sku,
             'supplier_name', l.supplier_name, 'quantity', l.quantity, 'master_status', l.master_status,
             'on_hand_before', l.on_hand_before, 'on_hand_set', l.on_hand_set, 'added', l.added,
             'on_hand_after', l.on_hand_after,
             'on_hand_now', case when p_warehouse_id is null then null else coalesce((
                select sl.on_hand from public.stock_levels sl
                 where sl.warehouse_id = p_warehouse_id and sl.jan_code = l.jan_code), 0) end)
           order by l.line_no)
      from public.master_import_lines l
      left join public.products p on p.id = l.product_id
     where l.import_id = p_id), '[]'::jsonb));
end;
$$;

