-- 0138 — one file, two stages: 商品マスタ first, then the stock in
-- 商品ライブラリー.
--
-- A file listing the goods to put in the warehouse (Excel, PDF, photo) is
-- chosen once and goes through:
--
--   1. 商品マスタ — every line's product is registered or brought up to date
--      by its JAN: our name, the English standard name, maker, 品番, unit, and
--      what this supplier calls it (supplier_product_names). Nothing is
--      written unless every line passes: a line without a valid JAN or a
--      name, or a JAN twice in the file, stops the whole file
--      (`master_import_commit` answers with the problems and changes
--      nothing). The screen then offers the other ways: correct the lines by
--      hand, or have the reading turned into an Excel sheet, check it, and
--      send that back. The original file and every converted or corrected
--      sheet are kept with the import and can be downloaded again.
--   2. 在庫 — once the master is through, each line's quantity is added to
--      that product's stock in the chosen warehouse, found by JAN. The stock
--      already there is shown first and can be corrected by hand before the
--      quantity is added. For every line the import keeps the stock it found,
--      the corrected figure, what was added and what it came to.
--
-- Both stages go through the ledger (apply_stock_movement_detail, ADJUST)
-- and stock_adjustments, so before + quantity = after still holds and the
-- stock_units projection follows. `stock_set_on_hand` corrects one product's
-- stock to a figure by hand at any time, the same way.

insert into storage.buckets (id, name, public, file_size_limit)
values ('master-import-files', 'master-import-files', false, 52428800)
on conflict (id) do nothing;

create table if not exists public.master_imports (
  id bigint generated by default as identity primary key,
  company_id bigint references public.companies (id),
  status text not null default 'reading'
    check (status in ('reading', 'stopped', 'master_done', 'stock_done', 'cancelled')),
  source text,
  supplier_id bigint references public.delivery_suppliers (id) on delete set null,
  warehouse_id bigint references public.warehouses (id),
  document_id bigint,
  original_name text,
  original_path text,
  original_type text,
  converted_name text,
  converted_path text,
  corrected_name text,
  corrected_path text,
  line_count integer not null default 0,
  issues jsonb not null default '[]'::jsonb,
  master_created integer not null default 0,
  master_updated integer not null default 0,
  master_mapped integer not null default 0,
  stock_lines integer not null default 0,
  stock_added integer not null default 0,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  master_at timestamptz,
  master_by uuid,
  stock_at timestamptz,
  stock_by uuid,
  updated_at timestamptz not null default now()
);
create index if not exists master_imports_created_idx on public.master_imports (created_at desc);

create table if not exists public.master_import_lines (
  id bigint generated by default as identity primary key,
  import_id bigint not null references public.master_imports (id) on delete cascade,
  line_no integer not null,
  jan_code text not null,
  product_id bigint references public.products (id) on delete set null,
  supplier_name text,
  name_en text,
  quantity integer not null default 0,
  master_status text check (master_status in ('new', 'updated')),
  -- Stage 2: the stock as found, as corrected by hand, what was added, and
  -- what it came to. Null until the stock is put in.
  on_hand_before integer,
  on_hand_set integer,
  added integer,
  on_hand_after integer,
  movement_ids bigint[] not null default '{}',
  created_at timestamptz not null default now(),
  unique (import_id, line_no)
);
create index if not exists master_import_lines_product_idx on public.master_import_lines (product_id);

