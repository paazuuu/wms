create or replace function public.set_serial_status(
  p_serial_id bigint,
  p_status text,
  p_note text default null
) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_status text := upper(btrim(coalesce(p_status, '')));
  v_found text;
begin
  if not (public.has_permission('inventory.adjust')
          or public.has_permission('product.manage')) then
    raise exception 'not permitted: inventory.adjust required';
  end if;
  if v_status not in ('IN_STOCK', 'SHIPPED', 'RETURNED', 'SCRAPPED', 'HOLD') then
    raise exception 'unknown serial status %', p_status;
  end if;

  update public.serial_numbers
     set status = v_status, note = coalesce(p_note, note), updated_at = now()
   where id = p_serial_id
  -- RETURNING gives back the row it wrote, so a null here means no row matched.
  returning status into v_found;
  if v_found is null then
    raise exception 'serial % not found', p_serial_id;
  end if;

  perform public.log_audit('product.serial_status', 'serial', p_serial_id::text,
    null, jsonb_build_object('status', v_status));
  return true;
end;
$$;

revoke all on function public.set_serial_status(bigint, text, text) from public, anon;
grant execute on function public.set_serial_status(bigint, text, text)
  to authenticated, service_role;

