  end if;
  v_id := public.upsert_serial(p_product_id, p_serial_number, v_lot_id, null, p_note);
  perform public.log_audit('product.serial_registered', 'product',
    p_product_id::text, null,
    jsonb_build_object('serial_id', v_id, 'lot_id', v_lot_id));
  return v_id;
end;
$$;

