  to authenticated, service_role;

-- The read §4 exists for. Deliberately not warehouse-scoped: a lot belongs to a
-- product, not to a building, and `lots` carries no warehouse — the same reason
-- list_products is not scoped. It becomes a per-warehouse number in Phase A
-- step 8, when stock rows start carrying `lot_id` and the question changes from
-- "which lots expire" to "how many of them are sitting in bin A-01".
create or replace function public.expiring_lots(
  p_days integer default 30,
  p_include_expired boolean default true
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_days integer := greatest(coalesce(p_days, 30), 0);
  v_expired boolean := coalesce(p_include_expired, true);
begin
  if not (public.has_permission('inventory.view')
          or public.has_permission('product.view')) then
    raise exception 'not permitted: inventory.view required';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'lot_id', l.id, 'lot_code', l.lot_code,
             'expiry_date', l.expiry_date,
             'days_to_expiry', l.expiry_date - current_date,
             'is_expired', l.expiry_date < current_date,
             'product_id', p.id, 'jan_code', p.jan_code, 'sku', p.sku,
             'product_name', p.name,
             'tracking_mode', p.tracking_mode,
             'serial_count', (select count(*) from public.serial_numbers sn
                               where sn.lot_id = l.id))
           order by l.expiry_date, p.name)
      from public.lots l
      join public.products p on p.id = l.product_id
     where l.expiry_date is not null
       and l.expiry_date <= current_date + v_days
       and (v_expired or l.expiry_date >= current_date)), '[]'::jsonb);
end;
$$;

revoke all on function public.expiring_lots(integer, boolean) from public, anon;
grant execute on function public.expiring_lots(integer, boolean)
  to authenticated, service_role;

-- §26 wants one resolver, so a scanned serial answers from the same call a
-- scanned barcode does. A serial label and a product barcode are physically
-- the same gesture at the same scan gun; making the operator pick the right
-- screen first is the kind of thing that gets skipped on the floor.
create or replace function public.resolve_barcode(p_barcode text)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_code text;
  v_raw text := nullif(upper(btrim(coalesce(p_barcode, ''))), '');
  v_result jsonb;
begin
  if not (public.has_permission('product.view')
          or public.has_permission('inventory.view')) then
    raise exception 'not permitted: product.view required';
  end if;

  v_code := public.normalize_barcode(p_barcode);
  if v_code is null then
    return jsonb_build_object('kind', 'unknown', 'barcode', p_barcode);
  end if;

  select jsonb_build_object(
           'kind', 'product',
           'barcode', b.barcode,
           'barcode_type', b.barcode_type,
           'quantity_per_scan', b.quantity_per_scan,
           'uom', (select u.code from public.uoms u where u.id = b.uom_id),
           'base_uom', (select u.code from public.uoms u where u.id = p.base_uom_id),
           'is_primary', b.is_primary,
           'product_id', p.id,
           'jan_code', p.jan_code,
           'sku', p.sku,
           'name', p.name,
           'category', p.category,
           'tracking_mode', p.tracking_mode,
           'status', p.status)
    into v_result
    from public.product_barcodes b
    join public.products p on p.id = b.product_id
   where b.barcode = v_code;
  if v_result is not null then
    return v_result;
  end if;

  -- Only after the barcode tables have had their say: a product barcode is the
  -- common case, and a serial that happens to look like one should still
  -- resolve as the product. Matched against both the raw uppercased input and
  -- the normalized code, because normalize_barcode strips the separators a
  -- serial may legitimately contain.
  select jsonb_build_object(
           'kind', 'serial',
           'barcode', sn.serial_number,
           'serial_id', sn.id,
           'serial_number', sn.serial_number,
           'serial_status', sn.status,
           'lot_id', sn.lot_id,
           'lot_code', (select l.lot_code from public.lots l where l.id = sn.lot_id),
           'expiry_date', (select l.expiry_date from public.lots l where l.id = sn.lot_id),
           'quantity_per_scan', 1,
           'base_uom', (select u.code from public.uoms u where u.id = p.base_uom_id),
           'product_id', p.id,
           'jan_code', p.jan_code,
           'sku', p.sku,
           'name', p.name,
           'category', p.category,
           'tracking_mode', p.tracking_mode,
           'status', p.status)
    into v_result
    from public.serial_numbers sn
    join public.products p on p.id = sn.product_id
   where sn.serial_number in (v_raw, v_code)
   order by case when sn.serial_number = v_raw then 0 else 1 end
   limit 1;

  return coalesce(v_result,
                  jsonb_build_object('kind', 'unknown', 'barcode', v_code));
end;
$$;

revoke all on function public.resolve_barcode(text) from public, anon;
grant execute on function public.resolve_barcode(text) to authenticated, service_role;

-- `inspection_detail` is the one existing read that already shows lot / serial /
-- expiry text, so it is where the resolved ids belong. Additive: the text
-- columns stay exactly as they are, and `lot_id` / `serial_id` / `lot_code`
-- appear beside them.
do $patch$
declare
  v_src text;
  v_new text;
  v_old constant text := $$'expiry', it.expiry,$$;
  v_add constant text := $$'expiry', it.expiry,
        'lot_id', it.lot_id,
        'serial_id', it.serial_id,
        'lot_code', (select l.lot_code from public.lots l where l.id = it.lot_id),
        'lot_expiry_date',
          (select l.expiry_date from public.lots l where l.id = it.lot_id),
        'serial_status',
          (select s.status from public.serial_numbers s where s.id = it.serial_id),$$;
begin
  select pg_get_functiondef(p.oid) into v_src
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'inspection_detail_impl';
  if v_src is null then
    raise exception 'inspection_detail_impl not found';
  end if;
  -- Asserted transform, same discipline as 0056: if the body has drifted from
  -- what this expects, the migration stops instead of silently doing nothing.
  if (length(v_src) - length(replace(v_src, v_old, ''))) / length(v_old) <> 1 then
    raise exception
      'inspection_detail_impl no longer contains exactly one %, refusing to patch it',
      v_old;
  end if;
  v_new := replace(v_src, v_old, v_add);
  execute v_new;
end $patch$;

