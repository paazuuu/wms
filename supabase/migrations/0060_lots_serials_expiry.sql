-- Phase A, steps 4-6: Lot / Serial / Expiry as first-class data (§4).
--
-- Today a lot, a serial and an expiry date are three free-text columns on
-- `inspection_items` — `lot`, `serial`, `expiry`. They are written once at
-- inspection and never read again, because there is nothing to read them
-- *from*: no row says "this lot expires on the 31st", so no screen can warn
-- about it and no picker can be told to take the older one first.
--
-- §4 asks for the two tables that make those answers possible. The three steps
-- are one migration because they are one shape: expiry lives on the lot, and a
-- serial points at the lot it came in. Splitting them would mean a `lots` table
-- with no date column and a `serial_numbers` table with nothing to point at.
--
-- 0057 put `products.tracking_mode` in place for exactly this moment. It stops
-- being decoration here: the mode decides whether a lot or a serial is allowed,
-- required, or refused, and it cannot be lowered once the data exists (§37-15).
--
-- WHAT MAKES THIS MORE THAN TWO EMPTY TABLES
--
-- A table nothing writes to is worse than no table: it looks like a feature.
-- So the existing inspection path feeds it. `inspection_items` gains `lot_id`
-- and `serial_id`, and a trigger resolves them from the text columns already
-- being filled in — the same 併走 (run-in-parallel) pattern 0058 used for
-- `product_id`, and for the same reason: the new column becomes correct on live
-- data without any screen changing first.
--
-- This is not §30 being bent. §30 says a scan or an AI produces a *candidate*
-- and a human confirms domain data. A product is master data somebody curates,
-- which is why 0058 refuses to invent one from an unknown JAN. A lot is not
-- master data — it is an observation of what physically arrived, typed in by the
-- inspector who is holding the box. Recording it is the confirmation.

-- ---------------------------------------------------------------------------
-- 1. Lots
-- ---------------------------------------------------------------------------

create table if not exists public.lots (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies (id),
  product_id bigint not null,
  -- Uppercased and trimmed on the way in (see upsert_lot). Separators are kept:
  -- "A-2024/05" is a lot code an operator will read back off a carton, and
  -- unlike a barcode there is no standard that says the punctuation is noise.
  lot_code text not null,
  manufacture_date date,
  expiry_date date,
  supplier_id bigint references public.delivery_suppliers (id),
  received_at timestamptz,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- The composite FK from 0057: a lot cannot end up under another company's
  -- product, because the pair has to match a real (company_id, id) row.
  constraint lots_product_fk foreign key (company_id, product_id)
    references public.products (company_id, id) on delete cascade,
  constraint lots_code_check check (lot_code = btrim(lot_code) and lot_code <> ''),
  constraint lots_dates_check check (
    manufacture_date is null or expiry_date is null or expiry_date >= manufacture_date),
  constraint lots_product_code_key unique (product_id, lot_code),
  -- Not redundant with the primary key: it is the target `serial_numbers` needs
  -- so that a serial's lot is provably a lot *of the same product*.
  constraint lots_product_id_key unique (product_id, id)
);

create index if not exists lots_expiry_idx on public.lots (expiry_date)
  where expiry_date is not null;
create index if not exists lots_supplier_idx on public.lots (supplier_id);

alter table public.lots enable row level security;

-- SELECT only, and no write policy at all: every write goes through a SECURITY
-- DEFINER function below, which is what lets the tracking-mode rules be the
-- single gate rather than something a direct PostgREST insert can walk around.
drop policy if exists "read lots" on public.lots;
create policy "read lots" on public.lots
  for select to authenticated
  using (public.has_permission('inventory.view')
         or public.has_permission('product.view'));

-- ---------------------------------------------------------------------------
-- 2. Serial numbers
-- ---------------------------------------------------------------------------

create table if not exists public.serial_numbers (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies (id),
  product_id bigint not null,
  serial_number text not null,
  lot_id bigint,
  status text not null default 'IN_STOCK',
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint serial_numbers_product_fk foreign key (company_id, product_id)
    references public.products (company_id, id) on delete cascade,
  -- Composite, so the lot belongs to the same product. `restrict` rather than
  -- `set null`: a lot with serials against it is not something to delete, and
  -- silently detaching the serial from its lot loses the link that made the
  -- serial traceable in the first place.
  constraint serial_numbers_lot_fk foreign key (product_id, lot_id)
    references public.lots (product_id, id) on delete restrict,
  constraint serial_numbers_value_check check (
    serial_number = btrim(serial_number) and serial_number <> ''),
  constraint serial_numbers_status_check check (
    status in ('IN_STOCK', 'SHIPPED', 'RETURNED', 'SCRAPPED', 'HOLD')),
  -- Company-wide, NOT per product. Two manufacturers can legitimately stamp the
  -- same serial on different goods, so this refuses something that is possible
  -- in the world — but a serial that resolves to two rows is useless at a scan
  -- gun, and resolving a bare serial is the whole point of recording it. When a
  -- genuine collision turns up, the operator prefixes one of them; that is a
  -- cheaper problem than an ambiguous scan.
  constraint serial_numbers_company_value_key unique (company_id, serial_number),
  -- The same FK target trick as lots: it lets a row that references a serial
  -- prove the serial is one of that product's.
  constraint serial_numbers_product_id_key unique (product_id, id)
);

create index if not exists serial_numbers_product_idx
  on public.serial_numbers (product_id, status);
create index if not exists serial_numbers_lot_idx on public.serial_numbers (lot_id);

alter table public.serial_numbers enable row level security;

drop policy if exists "read serial numbers" on public.serial_numbers;
create policy "read serial numbers" on public.serial_numbers
  for select to authenticated
  using (public.has_permission('inventory.view')
         or public.has_permission('product.view'));

-- ---------------------------------------------------------------------------
-- 3. The tracking mode stops being decoration
-- ---------------------------------------------------------------------------

-- 0057 defined five modes. Here is what each one actually means:
--
--   UNTRACKED       no lots, no serials. The default, and what every existing
--                   product is.
--   LOT             lots allowed; expiry optional.
--   EXPIRY          lots allowed and every lot MUST carry an expiry date. This
--                   is the food/medical case: the date is the thing being
--                   tracked and a lot without one is a gap in the record.
--   SERIAL          serials allowed; lots are not.
--   LOT_AND_SERIAL  both, and every serial must name its lot — otherwise the
--                   mode says it tracks two things while recording one.
--
-- Enforced by triggers rather than by the RPCs, so a future caller (a receiving
-- flow, an import, another trigger) cannot get it wrong by forgetting to ask.
create or replace function public.lot_tracking_ok()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_mode text;
begin
  select tracking_mode into v_mode from public.products where id = new.product_id;
  if v_mode is null then
    raise exception 'product % not found', new.product_id;
  end if;
  if v_mode not in ('LOT', 'LOT_AND_SERIAL', 'EXPIRY') then
    raise exception
      'product % has tracking_mode %; set it to LOT, LOT_AND_SERIAL or EXPIRY '
      'before recording lots', new.product_id, v_mode;
  end if;
  if v_mode = 'EXPIRY' and new.expiry_date is null then
    raise exception
      'product % tracks expiry, so lot % needs an expiry date',
      new.product_id, new.lot_code;
  end if;
  return new;
end;
$$;

drop trigger if exists lots_tracking_ok on public.lots;
create trigger lots_tracking_ok
  before insert or update on public.lots
  for each row execute function public.lot_tracking_ok();

create or replace function public.serial_tracking_ok()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_mode text;
begin
  select tracking_mode into v_mode from public.products where id = new.product_id;
  if v_mode is null then
    raise exception 'product % not found', new.product_id;
  end if;
  if v_mode not in ('SERIAL', 'LOT_AND_SERIAL') then
    raise exception
      'product % has tracking_mode %; set it to SERIAL or LOT_AND_SERIAL '
      'before recording serial numbers', new.product_id, v_mode;
  end if;
  if v_mode = 'LOT_AND_SERIAL' and new.lot_id is null then
    raise exception
      'product % tracks lot and serial, so serial % needs a lot',
      new.product_id, new.serial_number;
  end if;
  return new;
end;
$$;

drop trigger if exists serial_numbers_tracking_ok on public.serial_numbers;
create trigger serial_numbers_tracking_ok
  before insert or update on public.serial_numbers
  for each row execute function public.serial_tracking_ok();

-- The other direction, and the §37-15 half: the mode cannot be changed into one
-- that contradicts data already recorded under it. Dropping to UNTRACKED with
-- lots on file would not delete them — it would leave them unreachable and make
-- every past inspection that referenced one mean something else.
create or replace function public.tracking_mode_change_ok()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.tracking_mode = old.tracking_mode then
    return new;
  end if;

  if new.tracking_mode not in ('LOT', 'LOT_AND_SERIAL', 'EXPIRY')
     and exists (select 1 from public.lots where product_id = old.id) then
    raise exception
      'product % already has lots recorded; tracking_mode cannot become %',
      old.id, new.tracking_mode;
  end if;
  if new.tracking_mode not in ('SERIAL', 'LOT_AND_SERIAL')
     and exists (select 1 from public.serial_numbers where product_id = old.id) then
    raise exception
      'product % already has serial numbers recorded; tracking_mode cannot become %',
      old.id, new.tracking_mode;
  end if;
  -- Tightening is refused too when the existing rows would not satisfy the
  -- stricter mode, because the row triggers above only see rows being written.
  if new.tracking_mode = 'EXPIRY'
     and exists (select 1 from public.lots
                  where product_id = old.id and expiry_date is null) then
    raise exception
      'product % has lots with no expiry date; fill them in before switching to EXPIRY',
      old.id;
  end if;
  if new.tracking_mode = 'LOT_AND_SERIAL'
     and exists (select 1 from public.serial_numbers
                  where product_id = old.id and lot_id is null) then
    raise exception
      'product % has serial numbers with no lot; link them before switching to LOT_AND_SERIAL',
      old.id;
  end if;
  return new;
end;
$$;

drop trigger if exists products_tracking_mode_change_ok on public.products;
create trigger products_tracking_mode_change_ok
  before update of tracking_mode on public.products
  for each row execute function public.tracking_mode_change_ok();

