-- The internal upsert. No permission check, because its callers are the
-- permission-checked RPC below and the inspection trigger (whose caller already
-- passed `inspection.confirm`). Granted to nothing: only SECURITY DEFINER
-- callers reach it, and they run as the owner.
--
-- Idempotent on (product_id, lot_code): the second receipt of the same lot is
-- the same lot, and it may be the receipt that finally learns the expiry date.
-- Known dates are filled in, never overwritten with null.
create or replace function public.upsert_lot(
  p_product_id bigint,
  p_lot_code text default null,
  p_expiry_date date default null,
  p_manufacture_date date default null,
  p_supplier_id bigint default null,
  p_received_at timestamptz default null,
  p_note text default null
) returns bigint
language plpgsql security definer set search_path = ''
as $$
declare
  v_code text := nullif(upper(btrim(coalesce(p_lot_code, ''))), '');
  v_company_id bigint;
  v_id bigint;
begin
  select company_id into v_company_id from public.products where id = p_product_id;
  if v_company_id is null then
    raise exception 'product % not found', p_product_id;
  end if;

  -- An EXPIRY-tracked product often has no lot code on the carton at all — the
  -- date IS the identity. Deriving the code here, in one place, keeps
  -- `lot_code` the single handle every other query can rely on instead of
  -- spreading a nullable key through the schema.
  if v_code is null and p_expiry_date is not null then
    v_code := 'EXP-' || to_char(p_expiry_date, 'YYYYMMDD');
  end if;
  if v_code is null then
    raise exception 'a lot needs either a lot code or an expiry date';
  end if;

  insert into public.lots as l (company_id, product_id, lot_code, expiry_date,
                                manufacture_date, supplier_id, received_at, note)
  values (v_company_id, p_product_id, v_code, p_expiry_date,
          p_manufacture_date, p_supplier_id, coalesce(p_received_at, now()), p_note)
  on conflict (product_id, lot_code) do update
     set expiry_date      = coalesce(l.expiry_date, excluded.expiry_date),
         manufacture_date = coalesce(l.manufacture_date, excluded.manufacture_date),
         supplier_id      = coalesce(l.supplier_id, excluded.supplier_id),
         note             = coalesce(l.note, excluded.note),
         updated_at       = now()
  returning l.id into v_id;
  return v_id;
end;
$$;

revoke all on function
  public.upsert_lot(bigint, text, date, date, bigint, timestamptz, text)
  from public, anon, authenticated;

-- Same split, same reason.
create or replace function public.upsert_serial(
  p_product_id bigint,
  p_serial_number text,
  p_lot_id bigint default null,
  p_status text default null,
  p_note text default null
) returns bigint
language plpgsql security definer set search_path = ''
as $$
declare
  v_value text := nullif(upper(btrim(coalesce(p_serial_number, ''))), '');
  v_company_id bigint;
  v_owner bigint;
  v_id bigint;
begin
  if v_value is null then
    raise exception 'serial_number is required';
  end if;
  select company_id into v_company_id from public.products where id = p_product_id;
  if v_company_id is null then
    raise exception 'product % not found', p_product_id;
  end if;

  -- A serial identifies one physical unit, so the same string arriving against
  -- a different product is a data error worth naming rather than a second row
  -- the unique constraint would reject with a generic message.
  select product_id into v_owner from public.serial_numbers
   where company_id = v_company_id and serial_number = v_value;
  if v_owner is not null and v_owner <> p_product_id then
    raise exception 'serial % already belongs to product %', v_value, v_owner;
  end if;

  insert into public.serial_numbers as sn (company_id, product_id, serial_number,
                                          lot_id, status, note)
  values (v_company_id, p_product_id, v_value, p_lot_id,
          coalesce(nullif(upper(btrim(coalesce(p_status, ''))), ''), 'IN_STOCK'), p_note)
  on conflict (company_id, serial_number) do update
     set lot_id     = coalesce(excluded.lot_id, sn.lot_id),
         note       = coalesce(sn.note, excluded.note),
         updated_at = now()
  returning sn.id into v_id;
  return v_id;
end;
$$;

revoke all on function
  public.upsert_serial(bigint, text, bigint, text, text)
  from public, anon, authenticated;

-- The client-facing pair. `inventory.adjust` or `product.manage`: a lot is
-- recorded by whoever is receiving stock, not only by whoever curates the
-- product master.
create or replace function public.register_lot(
  p_product_id bigint,
  p_lot_code text default null,
  p_expiry_date date default null,
  p_manufacture_date date default null,
  p_supplier_id bigint default null,
  p_note text default null
) returns bigint
language plpgsql security definer set search_path = ''
as $$
declare
  v_id bigint;
begin
  if not (public.has_permission('inventory.adjust')
          or public.has_permission('product.manage')) then
    raise exception 'not permitted: inventory.adjust required';
  end if;
  v_id := public.upsert_lot(p_product_id, p_lot_code, p_expiry_date,
                            p_manufacture_date, p_supplier_id, null, p_note);
  perform public.log_audit('product.lot_registered', 'product', p_product_id::text,
    null, jsonb_build_object('lot_id', v_id,
      'lot_code', (select lot_code from public.lots where id = v_id),
      'expiry_date', p_expiry_date));
  return v_id;
end;
$$;

revoke all on function
  public.register_lot(bigint, text, date, date, bigint, text) from public, anon;
grant execute on function
  public.register_lot(bigint, text, date, date, bigint, text)
