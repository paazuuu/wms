create or replace function public.product_lots(p_product_id bigint)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not (public.has_permission('inventory.view')
          or public.has_permission('product.view')) then
    raise exception 'not permitted: inventory.view required';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', l.id, 'lot_code', l.lot_code,
             'expiry_date', l.expiry_date,
             'manufacture_date', l.manufacture_date,
             'received_at', l.received_at,
             'supplier_id', l.supplier_id,
             'supplier_name', (select s.name from public.delivery_suppliers s
                                where s.id = l.supplier_id),
             'days_to_expiry', case when l.expiry_date is null then null
                               else l.expiry_date - current_date end,
             'serial_count', (select count(*) from public.serial_numbers sn
                               where sn.lot_id = l.id),
             'note', l.note)
           -- Nulls last: a lot with no expiry is not "expiring soonest".
           order by l.expiry_date asc nulls last, l.lot_code)
      from public.lots l where l.product_id = p_product_id), '[]'::jsonb);
end;
$$;

revoke all on function public.product_lots(bigint) from public, anon;
grant execute on function public.product_lots(bigint) to authenticated, service_role;

create or replace function public.product_serials(
  p_product_id bigint,
  p_status text default null
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_status text := nullif(upper(btrim(coalesce(p_status, ''))), '');
begin
  if not (public.has_permission('inventory.view')
          or public.has_permission('product.view')) then
    raise exception 'not permitted: inventory.view required';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', sn.id, 'serial_number', sn.serial_number,
             'status', sn.status, 'lot_id', sn.lot_id,
             'lot_code', (select l.lot_code from public.lots l where l.id = sn.lot_id),
             'created_at', sn.created_at, 'note', sn.note)
           order by sn.serial_number)
      from public.serial_numbers sn
     where sn.product_id = p_product_id
       and (v_status is null or sn.status = v_status)), '[]'::jsonb);
end;
$$;

