-- Composite FKs, so an inspection line cannot cite a lot belonging to a
-- different product than the one it resolved. MATCH SIMPLE means the constraint
-- is satisfied whenever either column is null, which is what makes it safe to
-- add to a table whose `product_id` is still nullable (0058): unlinked rows are
-- unaffected, and a row with both set is checked.
do $fk$
begin
  if not exists (select 1 from pg_constraint
                  where conname = 'inspection_items_lot_fk'
                    and conrelid = 'public.inspection_items'::regclass) then
    alter table public.inspection_items
      add constraint inspection_items_lot_fk foreign key (product_id, lot_id)
        references public.lots (product_id, id) on delete restrict;
  end if;
  if not exists (select 1 from pg_constraint
                  where conname = 'inspection_items_serial_fk'
                    and conrelid = 'public.inspection_items'::regclass) then
    alter table public.inspection_items
      add constraint inspection_items_serial_fk foreign key (product_id, serial_id)
        references public.serial_numbers (product_id, id) on delete restrict;
  end if;
end $fk$;

create index if not exists inspection_items_lot_idx on public.inspection_items (lot_id);
create index if not exists inspection_items_serial_idx on public.inspection_items (serial_id);

-- Resolves `lot` / `serial` / `expiry` — columns the inspection screen already
-- fills in — into real rows, but only when the product is known and its mode
-- says so. An UNTRACKED product keeps the text and gets no lot: the operator
-- wrote something worth keeping, and inventing a lot the product does not track
-- would put a row in `lots` that nothing will ever look up.
--
-- Never overwrites an id a caller supplied, same as 0058's fill_product_id.
create or replace function public.fill_inspection_identity()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_mode text;
  v_lot text := nullif(btrim(coalesce(new.lot, '')), '');
  v_serial text := nullif(btrim(coalesce(new.serial, '')), '');
begin
  if new.product_id is null then
    return new;
  end if;
  select tracking_mode into v_mode from public.products where id = new.product_id;
  if v_mode is null or v_mode = 'UNTRACKED' then
    return new;
  end if;

  if new.lot_id is null
     and v_mode in ('LOT', 'LOT_AND_SERIAL', 'EXPIRY')
     and (v_lot is not null or new.expiry is not null) then
    new.lot_id := public.upsert_lot(new.product_id, v_lot, new.expiry);
  end if;

  if new.serial_id is null
     and v_serial is not null
     and v_mode in ('SERIAL', 'LOT_AND_SERIAL') then
    new.serial_id := public.upsert_serial(new.product_id, v_serial, new.lot_id);
  end if;
  return new;
end;
$$;

-- `zz` so it sorts after `inspection_items_fill_product_id` from 0058: Postgres
-- fires same-timing triggers in name order, and this one needs the product_id
-- that one resolves.
drop trigger if exists inspection_items_zz_fill_identity on public.inspection_items;
create trigger inspection_items_zz_fill_identity
  before insert or update of lot, serial, expiry, product_id, lot_id, serial_id
  on public.inspection_items
  for each row execute function public.fill_inspection_identity();

