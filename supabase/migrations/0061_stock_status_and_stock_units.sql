-- Everything the warehouse physically holds, in every condition.
create or replace function public.stock_on_hand(
  p_product_id bigint,
  p_warehouse_id bigint default null
) returns integer
language sql stable security definer set search_path = ''
as $$
  select coalesce(sum(su.quantity), 0)::integer
    from public.stock_units su
   where su.product_id = p_product_id
     and (p_warehouse_id is null or su.warehouse_id = p_warehouse_id)
     and public.can_access_warehouse(su.warehouse_id);
$$;

revoke all on function public.stock_on_hand(bigint, bigint) from public, anon;
grant execute on function public.stock_on_hand(bigint, bigint)
  to authenticated, service_role;

-- What can actually be shipped. Today that is on-hand in an available status;
-- step 12 subtracts reservations here, and the subtraction belongs *here* so
-- there is one definition of "available" rather than one per caller.
create or replace function public.stock_available(
  p_product_id bigint,
  p_warehouse_id bigint default null
) returns integer
language sql stable security definer set search_path = ''
as $$
  select coalesce(sum(su.quantity), 0)::integer
    from public.stock_units su
    join public.stock_statuses st on st.id = su.status_id
   where su.product_id = p_product_id
     and st.counts_available
     and (p_warehouse_id is null or su.warehouse_id = p_warehouse_id)
     and public.can_access_warehouse(su.warehouse_id);
$$;

revoke all on function public.stock_available(bigint, bigint) from public, anon;
grant execute on function public.stock_available(bigint, bigint)
  to authenticated, service_role;

create or replace function public.list_stock_statuses()
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not (public.has_permission('inventory.view')
          or public.has_permission('product.view')) then
    raise exception 'not permitted: inventory.view required';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', s.id, 'code', s.code, 'name', s.name,
             'counts_available', s.counts_available)
           order by s.sort_order, s.code)
      from public.stock_statuses s where s.is_active), '[]'::jsonb);
end;
$$;

