-- ---------------------------------------------------------------------------
-- 2. The stock unit
-- ---------------------------------------------------------------------------

-- One row per distinguishable parcel of stock: this product, in this warehouse,
-- from this lot, in this condition. `quantity` is in the product's base unit
-- (0059) — the conversions exist so a scan can say "one case"; what gets stored
-- is always pieces.
create table if not exists public.stock_units (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies (id),
  product_id bigint not null,
  warehouse_id bigint not null references public.warehouses (id),
  -- Reserved for step 9; the trigger below never sets it. See the header.
  bin_id bigint references public.bins (id),
  lot_id bigint,
  serial_id bigint,
  status_id bigint not null references public.stock_statuses (id),
  quantity integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint stock_units_product_fk foreign key (company_id, product_id)
    references public.products (company_id, id) on delete restrict,
  constraint stock_units_lot_fk foreign key (product_id, lot_id)
    references public.lots (product_id, id) on delete restrict,
  constraint stock_units_serial_fk foreign key (product_id, serial_id)
    references public.serial_numbers (product_id, id) on delete restrict,
  constraint stock_units_quantity_check check (quantity >= 0),
  -- A serial is one physical unit, so a parcel holding one cannot hold two.
  constraint stock_units_serial_quantity_check check (serial_id is null or quantity <= 1),
  -- NULLS NOT DISTINCT is the point: without it, every parcel with no lot and no
  -- serial would be distinct from every other, and the trigger would add a new
  -- row per movement instead of finding the one it should be adding to.
  constraint stock_units_identity_key unique nulls not distinct
    (product_id, warehouse_id, bin_id, lot_id, serial_id, status_id)
);

create index if not exists stock_units_warehouse_idx
  on public.stock_units (warehouse_id, product_id);
create index if not exists stock_units_lot_idx on public.stock_units (lot_id)
  where lot_id is not null;

alter table public.stock_units enable row level security;

-- Warehouse data, unlike lots and products: scoped, the same way every other
-- stock read has been since 0052.
drop policy if exists "read stock units" on public.stock_units;
create policy "read stock units" on public.stock_units
  for select to authenticated
  using (public.has_permission('inventory.view')
         and public.can_access_warehouse(warehouse_id));

-- ---------------------------------------------------------------------------
-- 3. The projection
-- ---------------------------------------------------------------------------

-- Adds to (or takes from) the parcels of one product in one warehouse, and
-- returns what it could not do — which is always zero when `stock_units` is in
-- step with the ledger, and is the drift when it is not.
--
-- Taking draws from the most available, soonest-expiring parcel first: an
-- outbound should consume the stock that is usable and closest to its date, and
-- should only reach into held or damaged stock when there is nothing else —
-- which in practice means the ledger and the parcels have drifted apart.
create or replace function public.apply_stock_unit_delta(
  p_product_id bigint,
  p_warehouse_id bigint,
  p_delta integer
) returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_company_id bigint;
  v_status_id bigint;
  v_left integer := abs(coalesce(p_delta, 0));
  v_take integer;
  v_row record;
begin
  if coalesce(p_delta, 0) = 0 then
    return 0;
  end if;
  select company_id into v_company_id from public.products where id = p_product_id;
  if v_company_id is null then
    return coalesce(p_delta, 0);
  end if;

  if p_delta > 0 then
    select id into v_status_id from public.stock_statuses where code = 'OK';
    insert into public.stock_units as su
      (company_id, product_id, warehouse_id, status_id, quantity)
    values (v_company_id, p_product_id, p_warehouse_id, v_status_id, p_delta)
    on conflict (product_id, warehouse_id, bin_id, lot_id, serial_id, status_id)
      do update set quantity = su.quantity + excluded.quantity, updated_at = now();
    return 0;
  end if;

  for v_row in
    select su.id, su.quantity
      from public.stock_units su
      join public.stock_statuses st on st.id = su.status_id
      left join public.lots l on l.id = su.lot_id
     where su.product_id = p_product_id
       and su.warehouse_id = p_warehouse_id
       and su.quantity > 0
     order by st.counts_available desc, l.expiry_date asc nulls last,
              st.sort_order, su.id
  loop
    exit when v_left <= 0;
    v_take := least(v_left, v_row.quantity);
    update public.stock_units
       set quantity = quantity - v_take, updated_at = now()
     where id = v_row.id;
    v_left := v_left - v_take;
  end loop;

  -- Empty parcels are not history — the ledger holds that — so they go rather
  -- than accumulating as a long tail of zero rows behind every product.
  delete from public.stock_units
   where product_id = p_product_id and warehouse_id = p_warehouse_id
     and quantity = 0 and serial_id is null;

  return -v_left;
end;
$$;

revoke all on function public.apply_stock_unit_delta(bigint, bigint, integer)
  from public, anon, authenticated;

-- The one writer. AFTER INSERT on the ledger, WAREHOUSE scope only, so this
-- cannot become a second source of truth: if it is not in the ledger, it is not
-- in `stock_units`.
create or replace function public.project_stock_movement()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_delta integer;
begin
  if coalesce(new.balance_scope, 'WAREHOUSE') <> 'WAREHOUSE' then
    return null;
  end if;
  -- A movement whose JAN no product accounts for cannot be projected onto a
  -- product. 0058 made that case visible and closable (unlinked_jan_codes);
  -- link the product and link_products_by_jan() fills the column, after which
  -- backfill_stock_units() brings the parcels up to date.
  if new.product_id is null then
    return null;
  end if;

  -- The signed effect of the row, taken from the balance it recorded rather
  -- than from `quantity` and a sign convention per movement_type.
  v_delta := new.quantity_after - new.quantity_before;
  perform public.apply_stock_unit_delta(new.product_id, new.warehouse_id, v_delta);
  return null;
end;
$$;

drop trigger if exists stock_movements_project_units on public.stock_movements;
create trigger stock_movements_project_units
  after insert on public.stock_movements
  for each row execute function public.project_stock_movement();

-- Brings `stock_units` to what `stock_levels` says, for every product the rows
-- can be attributed to. Safe to re-run: it computes the difference and applies
-- only that, so running it twice changes nothing the second time. This is the
-- function to run after `link_products_by_jan()` links a JAN that had stock
-- before its product existed.
create or replace function public.backfill_stock_units(
  p_warehouse_id bigint default null
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_row record;
  v_units integer;
  v_delta integer;
  v_adjusted integer := 0;
  v_skipped integer := 0;
begin
  for v_row in
    select sl.warehouse_id, sl.product_id, sl.jan_code, sl.on_hand
      from public.stock_levels sl
     where (p_warehouse_id is null or sl.warehouse_id = p_warehouse_id)
  loop
    if v_row.product_id is null then
      v_skipped := v_skipped + 1;
      continue;
    end if;
    select coalesce(sum(quantity), 0) into v_units
      from public.stock_units
     where product_id = v_row.product_id and warehouse_id = v_row.warehouse_id;
    v_delta := v_row.on_hand - v_units;
    if v_delta <> 0 then
      perform public.apply_stock_unit_delta(
        v_row.product_id, v_row.warehouse_id, v_delta);
      v_adjusted := v_adjusted + 1;
    end if;
  end loop;
  return jsonb_build_object('adjusted', v_adjusted, 'skipped_unlinked', v_skipped);
end;
$$;

revoke all on function public.backfill_stock_units(bigint) from public, anon;
grant execute on function public.backfill_stock_units(bigint) to service_role;

select public.backfill_stock_units();

-- ---------------------------------------------------------------------------
-- 4. Changing a parcel's condition
-- ---------------------------------------------------------------------------

-- Quarantining twenty of a hundred does not change what the warehouse holds; it
-- changes what can be shipped. So this moves quantity between two parcels of
-- the same product in the same warehouse and writes no ledger entry — the total
-- is untouched, which is exactly why the equality with `stock_levels` survives
-- it. Anything that *does* change the total is a stock movement instead.
create or replace function public.move_stock_status(
  p_product_id bigint,
  p_warehouse_id bigint,
  p_quantity integer,
  p_to_status text,
  p_from_status text default 'OK',
  p_note text default null
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_company_id bigint;
  v_from_id bigint;
  v_to_id bigint;
  v_available integer;
  v_left integer := coalesce(p_quantity, 0);
  v_take integer;
  v_row record;
begin
  if not public.has_permission('inventory.adjust') then
    raise exception 'not permitted: inventory.adjust required';
  end if;
  if not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;
  if v_left <= 0 then
    raise exception 'quantity must be greater than zero';
  end if;

  select id into v_from_id from public.stock_statuses
   where code = upper(btrim(coalesce(p_from_status, 'OK')));
  select id into v_to_id from public.stock_statuses
   where code = upper(btrim(coalesce(p_to_status, ''))) and is_active;
  if v_from_id is null then
    raise exception 'unknown stock status %', p_from_status;
  end if;
  if v_to_id is null then
    raise exception 'unknown stock status %', p_to_status;
  end if;
  if v_from_id = v_to_id then
    raise exception 'the stock is already %', upper(btrim(p_to_status));
  end if;

  select company_id into v_company_id from public.products where id = p_product_id;
  if v_company_id is null then
    raise exception 'product % not found', p_product_id;
  end if;

  select coalesce(sum(quantity), 0) into v_available
    from public.stock_units
   where product_id = p_product_id and warehouse_id = p_warehouse_id
     and status_id = v_from_id;
  if v_available < v_left then
    raise exception 'only % in %, cannot move %',
      v_available, upper(btrim(coalesce(p_from_status, 'OK'))), v_left;
  end if;

  -- Parcel by parcel, so a lot keeps its identity across the change: holding
  -- "20 of lot A" must not come out the other side as "20 of no lot".
  for v_row in
    select su.id, su.quantity, su.lot_id, su.serial_id, su.bin_id
      from public.stock_units su
      left join public.lots l on l.id = su.lot_id
     where su.product_id = p_product_id and su.warehouse_id = p_warehouse_id
       and su.status_id = v_from_id and su.quantity > 0
     order by l.expiry_date asc nulls last, su.id
  loop
    exit when v_left <= 0;
    v_take := least(v_left, v_row.quantity);

    insert into public.stock_units as su
      (company_id, product_id, warehouse_id, bin_id, lot_id, serial_id,
       status_id, quantity)
    values (v_company_id, p_product_id, p_warehouse_id, v_row.bin_id,
            v_row.lot_id, v_row.serial_id, v_to_id, v_take)
    on conflict (product_id, warehouse_id, bin_id, lot_id, serial_id, status_id)
      do update set quantity = su.quantity + excluded.quantity, updated_at = now();

    update public.stock_units
       set quantity = quantity - v_take, updated_at = now()
     where id = v_row.id;
    v_left := v_left - v_take;
  end loop;

  delete from public.stock_units
   where product_id = p_product_id and warehouse_id = p_warehouse_id
     and quantity = 0 and serial_id is null;

  perform public.log_audit('inventory.status_moved', 'product',
    p_product_id::text, p_warehouse_id,
    jsonb_build_object('quantity', p_quantity,
                       'from', upper(btrim(coalesce(p_from_status, 'OK'))),
                       'to', upper(btrim(p_to_status)), 'note', p_note));

  return jsonb_build_object(
    'product_id', p_product_id, 'warehouse_id', p_warehouse_id,
    'moved', p_quantity,
    'available', public.stock_available(p_product_id, p_warehouse_id));
end;
$$;

revoke all on function
  public.move_stock_status(bigint, bigint, integer, text, text, text)
  from public, anon;
grant execute on function
  public.move_stock_status(bigint, bigint, integer, text, text, text)
  to authenticated, service_role;

