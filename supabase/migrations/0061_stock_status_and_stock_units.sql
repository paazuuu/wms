-- Phase A, steps 7-8: Stock Status, and Stock Identity / Stock Unit (§5).
--
-- §5's complaint is that `on_hand = 100` is too weak a sentence. It cannot say
-- that twenty of those hundred are quarantined, that ten are damaged, or that
-- the oldest lot expires on Friday — and so it cannot answer the only question
-- an outbound flow actually asks, which is how many can be shipped *today*.
--
--     Available = on-hand that is usable  -  Reserved  -  Blocked/Hold etc.
--
-- and, the sentence that decides the whole design:
--
--     二重計上しないよう、実装上の正規ソースを決める
--     (pick the canonical source so nothing is counted twice)
--
-- WHAT IS ALREADY HERE, AND WHICH SOURCE IS CANONICAL
--
-- `stock_movements` is the ledger and stays the record of what happened (§37-4).
-- Two projections of it exist:
--
--   stock_levels  (warehouse, jan_code) -> on_hand, written by apply_stock_movement
--   bin_stock     (bin, jan_code)       -> on_hand, written by apply_bin_movement
--
-- They are not two copies of one number. A WAREHOUSE-scope movement changes what
-- the warehouse holds; a BIN-scope movement (put-away) only moves stock *inside*
-- the warehouse and leaves the total alone. `stock_movements.balance_scope` is
-- what keeps them apart, and no function writes both for one event.
--
-- `stock_units` joins that picture as a third projection of the same ledger —
-- never as a second writer. One trigger, on WAREHOUSE-scope movements only,
-- keeps it in step with `stock_levels`, so for every warehouse:
--
--     sum(stock_units.quantity) == stock_levels.on_hand
--
-- That equality is the whole safety property. `stock_reconciliation()` checks it
-- on demand, and everything below is arranged so it cannot quietly stop holding.
--
-- WHAT THIS DELIBERATELY DOES NOT DO
--
-- **Bins.** `stock_units.bin_id` exists and stays null. Putting bin granularity
-- in here would mean modelling put-away as a transfer between parcels, and a
-- put-away that outruns its receipt would either drive a parcel negative or
-- silently break the equality above. Bins are step 9's subject, where the
-- location tree is what is actually being worked on; `bin_stock` remains the
-- bin-level answer until then.
--
-- **RESERVED and ALLOCATED are not statuses.** They are in §5's list, but a
-- reserved unit is still physically on hand and still in its own condition —
-- making RESERVED a bucket would move the quantity out of OK and count the
-- reservation twice, once as a missing unit and once as a claim. They become
-- rows in their own table in step 12, and `available` subtracts them there.
--
-- **Every status counts toward on-hand.** Statuses differ only in whether they
-- are *available*. Scrapping is not a status change; it is a stock movement
-- that reduces the total, and it leaves a ledger entry the way §37-4 requires.
-- This is what lets a status change always conserve the warehouse total, which
-- is what keeps the equality above true without a second ledger.

-- ---------------------------------------------------------------------------
-- 1. The status vocabulary
-- ---------------------------------------------------------------------------

create table if not exists public.stock_statuses (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  -- The §5 formula, as data rather than as a list of codes buried in a query.
  -- There is no `counts_on_hand`: every status does (see the header).
  counts_available boolean not null default false,
  sort_order integer not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint stock_statuses_code_key unique (code),
  constraint stock_statuses_code_check check (code = upper(btrim(code)) and code <> '')
);

