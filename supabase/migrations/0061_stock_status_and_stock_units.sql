-- The screen §5 is asking for: not one number, but the split that explains it.
create or replace function public.stock_status_breakdown(
  p_product_id bigint default null,
  p_warehouse_id bigint default null
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.has_permission('inventory.view') then
    raise exception 'not permitted: inventory.view required';
  end if;
  if p_warehouse_id is not null and not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;

  return coalesce((
    select jsonb_agg(row_to_json(t)::jsonb order by t.product_name, t.warehouse_id)
      from (
        select su.product_id,
               p.name as product_name,
               p.jan_code,
               p.sku,
               su.warehouse_id,
               w.name as warehouse_name,
               sum(su.quantity)::integer as on_hand,
               coalesce(sum(su.quantity) filter (where st.counts_available), 0)::integer
                 as available,
               jsonb_agg(jsonb_build_object(
                 'status', st.code, 'name', st.name,
                 'quantity', su.quantity,
                 'lot_id', su.lot_id,
                 'lot_code', (select l.lot_code from public.lots l where l.id = su.lot_id),
                 'expiry_date', (select l.expiry_date from public.lots l where l.id = su.lot_id))
                 order by st.sort_order) as parcels
          from public.stock_units su
          join public.stock_statuses st on st.id = su.status_id
          join public.products p on p.id = su.product_id
          join public.warehouses w on w.id = su.warehouse_id
         where (p_product_id is null or su.product_id = p_product_id)
           and (p_warehouse_id is null or su.warehouse_id = p_warehouse_id)
           -- Null warehouse means "every warehouse I may see", never "all".
           and public.can_access_warehouse(su.warehouse_id)
         group by su.product_id, p.name, p.jan_code, p.sku, su.warehouse_id, w.name
      ) t), '[]'::jsonb);
end;
$$;

revoke all on function public.stock_status_breakdown(bigint, bigint) from public, anon;
grant execute on function public.stock_status_breakdown(bigint, bigint)
  to authenticated, service_role;

-- The safety property, made checkable. Every row it returns is a place where
-- the parcels and the ledger's own projection disagree, which means either a
-- movement that could not be attributed to a product (0058's unlinked JANs) or
-- a writer that has gone around the trigger. An empty result is the invariant
-- holding.
create or replace function public.stock_reconciliation(
  p_warehouse_id bigint default null
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.has_permission('inventory.view') then
    raise exception 'not permitted: inventory.view required';
  end if;
  if p_warehouse_id is not null and not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;

  return coalesce((
    select jsonb_agg(row_to_json(t)::jsonb order by t.warehouse_id, t.jan_code)
      from (
        select sl.warehouse_id,
               sl.jan_code,
               sl.product_id,
               sl.on_hand as stock_levels_on_hand,
               coalesce((select sum(su.quantity) from public.stock_units su
                          where su.product_id = sl.product_id
                            and su.warehouse_id = sl.warehouse_id), 0)::integer
                 as stock_units_on_hand,
               case when sl.product_id is null then 'unlinked jan_code'
                    else 'quantity drift' end as reason
          from public.stock_levels sl
         where (p_warehouse_id is null or sl.warehouse_id = p_warehouse_id)
           and public.can_access_warehouse(sl.warehouse_id)
           and (sl.product_id is null
                or sl.on_hand <> coalesce((select sum(su.quantity)
                                             from public.stock_units su
                                            where su.product_id = sl.product_id
                                              and su.warehouse_id = sl.warehouse_id), 0))
      ) t), '[]'::jsonb);
end;
$$;

revoke all on function public.stock_reconciliation(bigint) from public, anon;
grant execute on function public.stock_reconciliation(bigint)
  to authenticated, service_role;

