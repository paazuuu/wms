create or replace function public.pick_wave_detail(p_wave_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $$
declare
  v_warehouse bigint;
begin
  select warehouse_id into v_warehouse from public.pick_waves where id = p_wave_id;
  if v_warehouse is null then raise exception 'wave % not found', p_wave_id; end if;
  if not public.can_access_warehouse(v_warehouse) then
    raise exception 'not permitted: warehouse.scope required';
  end if;

  return (
    select jsonb_build_object(
      'id', w.id,
      'code', w.code,
      'warehouse_id', w.warehouse_id,
      'warehouse_name', wh.name,
      'status', w.status,
      'assigned_to', w.assigned_to,
      'assigned_to_name', u.name,
      'priority', w.priority,
      'note', w.note,
      'created_at', w.created_at,
      'started_at', w.started_at,
      'completed_at', w.completed_at,
      'task_count', (select count(*) from public.pick_tasks t
                      join public.pick_lists l on l.id = t.pick_list_id
                     where l.wave_id = w.id),
      'picked_count', (select count(*) from public.pick_tasks t
                        join public.pick_lists l on l.id = t.pick_list_id
                       where l.wave_id = w.id and t.picked_quantity is not null),
      'lists', coalesce((
        select jsonb_agg(jsonb_build_object(
                 'pick_list_id', l.id,
                 'shipment_plan_id', l.shipment_plan_id,
                 'shipment_number', p.shipment_number,
                 'customer_name', p.customer_name,
                 'status', l.status,
                 'task_count', (select count(*) from public.pick_tasks t
                                 where t.pick_list_id = l.id),
                 'picked_count', (select count(*) from public.pick_tasks t
                                   where t.pick_list_id = l.id
                                     and t.picked_quantity is not null))
               order by l.id)
          from public.pick_lists l
          join public.shipment_plans p on p.id = l.shipment_plan_id
         where l.wave_id = w.id), '[]'::jsonb))
    from public.pick_waves w
    left join public.warehouses wh on wh.id = w.warehouse_id
    left join public.app_users u on u.id = w.assigned_to
   where w.id = p_wave_id);
end;
$$;

revoke all on function public.pick_wave_detail(bigint) from public, anon;
grant execute on function public.pick_wave_detail(bigint) to authenticated, service_role;

create or replace function public.pick_wave_index(
  p_warehouse_id bigint default null,
  p_status text default null,
  p_limit integer default 50
) returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $$
declare
  v_status text := nullif(upper(btrim(coalesce(p_status, ''))), '');
begin
  if p_warehouse_id is not null and not public.can_access_warehouse(p_warehouse_id) then
    raise exception 'not permitted: warehouse.scope required';
  end if;

  return coalesce((
    select jsonb_agg(row_to_json(x)::jsonb order by x.priority, x.id desc)
      from (
        select w.id, w.code, w.warehouse_id, wh.name as warehouse_name,
               w.status, w.priority, w.assigned_to, u.name as assigned_to_name,
               w.created_at, w.started_at, w.completed_at,
               (select count(*) from public.pick_lists l where l.wave_id = w.id)
                 as list_count,
               (select count(*) from public.pick_tasks t
                  join public.pick_lists l on l.id = t.pick_list_id
                 where l.wave_id = w.id) as task_count,
               (select count(*) from public.pick_tasks t
                  join public.pick_lists l on l.id = t.pick_list_id
                 where l.wave_id = w.id and t.picked_quantity is not null)
                 as picked_count
          from public.pick_waves w
          left join public.warehouses wh on wh.id = w.warehouse_id
          left join public.app_users u on u.id = w.assigned_to
         where (p_warehouse_id is null or w.warehouse_id = p_warehouse_id)
           and (v_status is null or w.status = v_status)
           and public.can_access_warehouse(w.warehouse_id)
         order by w.priority, w.id desc
         limit greatest(1, least(coalesce(p_limit, 50), 200))
      ) x), '[]'::jsonb);
end;
$$;

revoke all on function public.pick_wave_index(bigint, text, integer) from public, anon;
grant execute on function public.pick_wave_index(bigint, text, integer)
  to authenticated, service_role;
